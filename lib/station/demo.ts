/** 決まった種から評価を作る（毎回同じ見本になるように。Math.random は使わない） */
function ratingsFrom(seed: number, n: number, base: [number, number, number]): Rating[] {
  const out: Rating[] = [];
  let s = seed;
  for (let i = 0; i < n; i++) {
    s = (s * 9301 + 49297) % 233280;
    const r = s / 233280;
    const bump = (k: number) => Math.max(0, Math.min(3, base[k] + (r > 0.75 ? 1 : r < 0.2 ? -1 : 0) * (k === i % 3 ? 1 : 0)));
    out.push({ clear: bump(0), care: bump(1), again: bump(2) });
  }
  return out;
}

