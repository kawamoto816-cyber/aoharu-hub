function S(n: number, id: string, unit: string, title: string, lead: string, ptitle: string, body: string, pick: number, questions: Question[], notes?: { word: string; meaning: string }[]): ExamPoolSection {
  return {
    unit,
    tag: `${K}:${n}`,
    section: {
      id: `kbk-${id}`,
      title,
      lead,
      style: "reading",
      examOnly: true,
      pick,
      material: [{ kind: "passage", lang: "ja", ...(ptitle ? { title: ptitle } : {}), body, ...(notes ? { notes } : {}) }],
      questions,
    },
  };
}

