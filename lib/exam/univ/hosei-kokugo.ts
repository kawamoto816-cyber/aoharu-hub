const steps = (s: St) => s.map(([title, body]) => ({ title, body }));
const sec = (d: D) => (d === 1 ? 50 : d === 2 ? 80 : 110);
const pts = (d: D) => (d === 1 ? 3 : d === 2 ? 4 : 5);

/** 4択 (正解は options[0]。画面では並べかえる) */
function ch(id: string, d: D, unit: string, prompt: string, options: string[], why: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: sec(d),
    skill: d === 1 ? "知識・技能" : "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "choice", options, correct: 0, why },
    point,
    steps: steps(st),
  };
}

/** 漢字（選択式：同じ漢字を用いるもの） */
function kc(id: string, prompt: string, options: string[], why: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: 1,
    points: 2,
    seconds: 40,
    skill: "知識・技能",
    unit: KANJI,
    prompt,
    answer: { kind: "choice", options, correct: 0, why },
    point,
    steps: steps(st),
  };
}

/** 抜き出し (字数つき) */
function nk(id: string, d: D, prompt: string, accept: string[], chars: number, point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: 120,
    skill: "思考・判断・表現",
    unit: RONRI,
    prompt,
    answer: { kind: "term", accept, chars },
    point,
    steps: steps(st),
  };
}

/** 記述 (type C・毎回出る。rubric の合計が配点) */
function wr(id: string, prompt: string, max: number, model: string, rubric: [string, number, string[]][], point: string, st: St): Question {
  return {
    id,
    type: "C",
    difficulty: 3,
    points: rubric.reduce((s, r) => s + r[1], 0),
    seconds: 420,
    skill: "思考・判断・表現",
    unit: RONRI,
    prompt,
    answer: { kind: "written", limit: { max, unit: "字" }, model, rubric: rubric.map(([label, p, keywords]) => ({ label, points: p, keywords })) },
    point,
    steps: steps(st),
  };
}

