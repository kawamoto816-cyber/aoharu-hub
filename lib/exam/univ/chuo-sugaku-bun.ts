const KEY = "chuo-sugaku-bun";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD = "次の問いに答えよ。(1) は答えのみでよい。(2)(3) は答えだけでなく、途中の過程も記述せよ。";

type St = ([string, string] | [string, string, string])[];
type Rub = { label: string; points: number; keywords?: string[] }[];
const steps = (st: St) => st.map(([title, body, trap]) => (trap ? { title, body, trap } : { title, body }));

interface N {
  id: string;
  u: string;
  p: string;
  a: Omit<NumQ, "kind">;
  pt: string;
  st: St;
}
/** (1) 答えのみの数値 (自動採点)。難易度1・7点 */
function nm(q: N): QuestionC {
  return {
    id: q.id,
    type: "C",
    difficulty: 1,
    points: 7,
    seconds: 180,
    skill: "知識・技能",
    unit: q.u,
    prompt: q.p,
    answer: { kind: "num", ...q.a },
    point: q.pt,
    steps: steps(q.st),
  };
}

interface W {
  id: string;
  u: string;
  d: Difficulty;
  p: string;
  model: string;
  rub: Rub;
  auto?: Omit<NumQ, "kind">;
  dep: string;
  pt: string;
  st: St;
}
/** (2)(3) 記述 (模範解答と採点基準で自己採点。最後の数値は autoPart) */
function wr(q: W): QuestionC {
  const points = q.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: q.id,
    type: "C",
    difficulty: q.d,
    points,
    seconds: q.d === 3 ? 420 : 300,
    skill: "思考・判断・表現",
    unit: q.u,
    dependsOn: q.dep,
    prompt: q.p,
    answer: { kind: "written", model: q.model, rubric: q.rub, ...(q.auto ? { autoPart: { kind: "num", ...q.auto } } : {}) },
    point: q.pt,
    steps: steps(q.st),
  };
}

function sec(tag: number, id: string, unit: string, title: string, body: string, qs: QuestionC[]): ExamPoolSection {
  return {
    unit,
    tag: TAG(tag),
    section: {
      id: `chuo-sugaku-${tag}-${id}`,
      title,
      lead: LEAD,
      material: [{ kind: "text" as const, body }],
      questions: qs,
    },
  };
}

