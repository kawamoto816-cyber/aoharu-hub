const steps = (s: St) => s.map(([title, body]) => ({ title, body }));

/** 記述（type C・毎回出る。rubric の合計が配点。max は解答欄の目安の字数） */
function wr(id: string, d: 2 | 3, unit: string, prompt: string, max: number, model: string, rubric: Rub, point: string, st: St): QuestionC {
  const points = rubric.reduce((s, r) => s + r[1], 0);
  return {
    id,
    type: "C",
    difficulty: d,
    points,
    seconds: Math.round(max * 4 + 120),
    skill: "思考・判断・表現",
    unit,
    prompt: `${prompt}（目安${max}字）`,
    answer: {
      kind: "written",
      limit: { min: Math.floor(max * 0.5), max, unit: "字" },
      model,
      rubric: rubric.map(([label, p, keywords]) => ({ label, points: p, keywords })),
    },
    point,
    steps: steps(st),
  };
}

