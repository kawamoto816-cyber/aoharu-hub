function S(n: number, id: string, unit: string, title: string, ptitle: string, body: string, questions: QuestionC[], notes?: { word: string; meaning: string }[]): ExamPoolSection {
  return {
    unit,
    tag: `${K}:${n}`,
    section: {
      id: `kyk-${id}`,
      title,
      lead: n === 3 ? LEAD3 : LEAD1,
      style: "reading",
      examOnly: true,
      material: [{ kind: "passage", lang: "ja", ...(ptitle ? { title: ptitle } : {}), body, ...(notes ? { notes } : {}) }],
      questions,
    },
  };
}

