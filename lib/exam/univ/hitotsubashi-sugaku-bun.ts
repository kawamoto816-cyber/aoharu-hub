const KEY = "hitotsubashi-sugaku-bun";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD = "次の問いに答えよ。答えだけでなく、途中の考え方や式も記述すること。";

type St = [string, string, string?][];
type Rub = { label: string; points: number; keywords?: string[] }[];
interface W {
  id: string;
  u: string;
  d: Difficulty;
  p: string;
  model: string;
  rub: Rub;
  pt: string;
  st: St;
  auto?: NumQ;
  dep?: string;
  /** 知識・技能 (計算が中心の小問) */
  k?: boolean;
  sec?: number;
}

function wr(a: W): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  const skill: Skill = a.k ? "知識・技能" : "思考・判断・表現";
  return {
    id: a.id,
    type: "C",
    difficulty: a.d,
    points,
    seconds: a.sec ?? (a.d === 3 ? 720 : a.d === 2 ? 540 : 360),
    skill,
    unit: a.u,
    ...(a.dep ? { dependsOn: a.dep } : {}),
    prompt: a.p,
    answer: { kind: "written", model: a.model, rubric: a.rub, ...(a.auto ? { autoPart: a.auto } : {}) },
    point: a.pt,
    steps: a.st.map(([title, body, trap]) => ({ title, body, ...(trap ? { trap } : {}) })),
  };
}

const num = (answer: string, calc: string, labels?: string[]): NumQ => ({ kind: "num", answerKind: "num", answer: [answer], calc, ...(labels ? { labels } : {}) });
const surd = (answer: string, calc: string, labels?: string[]): NumQ => ({ kind: "num", answerKind: "surd", answer: [answer], calc, ...(labels ? { labels } : {}) });

function sec(tag: number, id: string, unit: string, title: string, body: string, qs: QuestionC[]): ExamPoolSection {
  return {
    unit,
    tag: TAG(tag),
    section: {
      id: `hitotsu-math-${tag}-${id}`,
      title,
      lead: LEAD,
      material: [{ kind: "text", body }],
      questions: qs,
    },
  };
}

