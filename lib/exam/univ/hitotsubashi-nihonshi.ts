type St = [string, string][];
type Rub = { label: string; points: number; keywords?: string[] }[];

/** 論述 (毎回出す)。points は採点基準の合計 */
function wr(a: { id: string; u: string; no?: string; p: string; max: number; model: string; rub: Rub; pt: string; st: St }): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  const d: Difficulty = a.max >= 300 ? 3 : 2;
  return {
    id: a.id,
    type: "C",
    difficulty: d,
    points,
    seconds: a.max * 6,
    skill: "思考・判断・表現",
    unit: a.u,
    ...(a.no ? { no: a.no } : {}),
    prompt: a.p,
    answer: { kind: "written", limit: { min: Math.round(a.max * 0.8), max: a.max, unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: a.st.map(([title, body]) => ({ title, body })),
  };
}

