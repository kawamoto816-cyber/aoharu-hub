function sec(unit: string, tag: string, id: string, title: string, body: string, questions: QuestionC[]): ExamPoolSection {
  return { unit, tag, section: { id, title, lead: LEAD, examOnly: true, style: "writing", material: [{ kind: "passage", lang: "ja", body }], questions } };
}

