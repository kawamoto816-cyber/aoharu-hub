const KEY = "todai-sekaishi";
const TAG = (i: number) => `${KEY}:${i}`;

type St = [string, string][];
type Rub = { label: string; points: number; keywords?: string[] }[];
const steps = (st: St) => st.map(([title, body]) => ({ title, body }));

/** 論述 (毎回出す)。max は字数の上限、下限はその8割 */
function wr(a: { id: string; u: string; d?: Difficulty; p: string; max: number; model: string; rub: Rub; pt: string; st: St }): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: a.id,
    type: "C",
    difficulty: a.d ?? (a.max >= 120 ? 3 : 2),
    points,
    seconds: a.max >= 600 ? 2100 : a.max >= 120 ? 480 : a.max >= 90 ? 360 : 240,
    skill: "思考・判断・表現",
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", limit: { min: Math.round(a.max * 0.8), max: a.max, unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: steps(a.st),
  };
}

/** 語句の記述 (any=カタカナなどでもよい) */
function tm(a: { id: string; u: string; d: Difficulty; p: string; acc: string[]; any?: boolean; pt: string; st: St }): QuestionB {
  return {
    id: a.id,
    type: "B",
    difficulty: a.d,
    points: a.d === 3 ? 2 : 1,
    seconds: a.d === 3 ? 60 : 40,
    skill: "知識・技能",
    unit: a.u,
    prompt: a.p,
    answer: { kind: "term", accept: a.acc, script: a.any ? "any" : "kanji" },
    point: a.pt,
    steps: steps(a.st),
  };
}

