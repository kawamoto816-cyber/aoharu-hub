// 日本史は文学部だけで選べる (外国語学部の地歴は世界史のみ)。
// 問題・資料文はすべてこの型のために書き下ろしたもの (過去問の文・設問は使っていない)。史料は原典 (武家諸法度・御成敗式目) から短く引いた。
// 参考:
//   https://www.osaka-u.ac.jp/ja/admissions/faculty/general/files/rdvbt/@@download/file (令和7年度 地理歴史 解答例・出題の意図: 日本史は大問4題・古代〜近現代)
//   https://www.osaka-u.ac.jp/ja/admissions/faculty/general/files/ocrbub/@@download/file (令和6年度 地理歴史 解答例・出題の意図)
//   https://jyuke-labo.com/daigakujyukentaisaku/osakadaigaku/nihonshi/ (90分・大問4題・各200字程度の論述)

const KEY = "handai-nihonshi";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD = "次の文章を読み、問いに答えよ。解答は200字程度で書け。";

type Rub = { label: string; points: number; keywords?: string[] }[];

/** 200字程度の論述 1問だけの節 */
function ron(a: {
  id: string;
  unit: string;
  tag: number;
  title: string;
  body: string;
  p: string;
  model: string;
  rub: Rub;
  pt: string;
  st: [string, string][];
}): ExamPoolSection {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  const q: QuestionC = {
    id: "ronjutsu",
    type: "C",
    difficulty: 3,
    points,
    seconds: 1260,
    skill: "思考・判断・表現",
    unit: a.unit,
    prompt: a.p,
    answer: { kind: "written", limit: { min: 180, max: 220, unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: a.st.map(([title, body]) => ({ title, body })),
  };
  return {
    unit: a.unit,
    tag: TAG(a.tag),
    section: {
      id: `handai-nihon-${a.tag}-${a.id}`,
      title: a.title,
      lead: LEAD,
      material: [{ kind: "passage", lang: "ja", body: a.body }],
      questions: [q],
      style: "writing",
      examOnly: true,
    },
  };
}

