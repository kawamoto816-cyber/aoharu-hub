const KEY = "kyodai-sugaku-bun";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD = "次の問いに答えよ。解答は、答えだけでなく、考え方や途中の計算・論証も書くこと。";

type St = [string, string, string?][];
type Rub = { label: string; points: number; keywords?: string[] }[];
interface W {
  id: string;
  u: string;
  d?: Difficulty;
  /** 目安時間 (秒) */
  s?: number;
  p: string;
  model: string;
  rub: Rub;
  auto?: NumQ;
  pt: string;
  st: St;
  dep?: string;
}

function wr(a: W): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: a.id,
    type: "C",
    difficulty: a.d ?? 2,
    points,
    seconds: a.s ?? 480,
    skill: "思考・判断・表現",
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", model: a.model, rubric: a.rub, ...(a.auto ? { autoPart: a.auto } : {}) },
    point: a.pt,
    steps: a.st.map(([title, body, trap]) => ({ title, body, ...(trap ? { trap } : {}) })),
    ...(a.dep ? { dependsOn: a.dep } : {}),
  };
}

const num = (answer: string, calc: string, unit?: string): NumQ => ({ kind: "num", answerKind: "num", answer: [answer], calc, ...(unit ? { unit } : {}) });
const surd = (answer: string, eq: string): NumQ => ({ kind: "num", answerKind: "surd", answer: [answer], equations: [eq] });

function sec(tag: number, id: string, unit: string, title: string, qs: QuestionC[]): ExamPoolSection {
  return { unit, tag: TAG(tag), section: { id: `kyodai-sbun-${tag}-${id}`, title, lead: LEAD, questions: qs } };
}

