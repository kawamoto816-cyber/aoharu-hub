const KEY = "hokudai-sugaku-bun";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD = "次の問いに答えよ。答えだけでなく、結果を導く過程も記述せよ。";

type St = [string, string, string?][];
type Rub = { label: string; points: number; keywords?: string[] }[];
interface W {
  id: string;
  u: string;
  d: Difficulty;
  p: string;
  model: string;
  rub: Rub;
  pt: string;
  st: St;
  auto?: NumQ;
  dep?: string;
  sec?: number;
}

function wr(a: W): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: a.id,
    type: "C",
    difficulty: a.d,
    points,
    seconds: a.sec ?? (a.d === 1 ? 360 : a.d === 2 ? 420 : 540),
    skill: "思考・判断・表現",
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", model: a.model, rubric: a.rub, ...(a.auto ? { autoPart: a.auto } : {}) },
    point: a.pt,
    steps: a.st.map(([title, body, trap]) => ({ title, body, ...(trap ? { trap } : {}) })),
    ...(a.dep ? { dependsOn: a.dep } : {}),
  };
}

const num = (answer: string, calc: string, extra: Partial<NumQ> = {}): NumQ => ({ kind: "num", answerKind: "num", answer: [answer], calc, ...extra });
const numEq = (answer: string, equations: string[], extra: Partial<NumQ> = {}): NumQ => ({ kind: "num", answerKind: "num", answer: [answer], equations, ...extra });
const surd = (answer: string, equations: string[], extra: Partial<NumQ> = {}): NumQ => ({ kind: "num", answerKind: "surd", answer: [answer], equations, ...extra });
const pair = (a: string, b: string, equations: string[], labels: string[]): NumQ => ({ kind: "num", answerKind: "pair", answer: [a, b], equations, labels });

function sec(tag: number, id: string, unit: string, title: string, body: string, qs: QuestionC[]): ExamPoolSection {
  return {
    unit,
    tag: TAG(tag),
    section: {
      id: `hokudai-sb-${tag}-${id}`,
      title,
      lead: LEAD,
      material: [{ kind: "text", body }],
      questions: qs,
    },
  };
}

