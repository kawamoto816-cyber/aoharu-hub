const KB = "（返り点は（ ）の中に示し、送り仮名は省いた。）";

function S(n: number, id: string, unit: string, title: string, lead: string, ptitle: string, body: string, questions: Question[], notes?: { word: string; meaning: string }[]): ExamPoolSection {
  return {
    unit,
    tag: `${K}:${n}`,
    section: {
      id: `hkk-${id}`,
      title,
      lead,
      style: "reading",
      examOnly: true,
      material: [{ kind: "passage", lang: "ja", ...(ptitle ? { title: ptitle } : {}), body, ...(notes ? { notes } : {}) }],
      questions,
    },
  };
}

