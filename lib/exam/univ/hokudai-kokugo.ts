const steps = (s: St) => s.map(([title, body]) => ({ title, body }));

/** 漢字の書き取り */
function kj(id: string, d: D, prompt: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: 40,
    skill: "知識・技能",
    unit: KANJI,
    prompt,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

/** 漢文の読み (ひらがなで書く) */
function ym(id: string, d: D, unit: string, prompt: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: 45,
    skill: "知識・技能",
    unit,
    prompt,
    answer: { kind: "term", accept, script: "hira" },
    point,
    steps: steps(st),
  };
}

/** 記述 (type C・毎回出る。rubric の合計が配点。max は解答欄の目安の字数) */
function wr(id: string, d: 2 | 3, unit: string, prompt: string, max: number, model: string, rubric: Rb, point: string, st: St): Question {
  return {
    id,
    type: "C",
    difficulty: d,
    points: rubric.reduce((s, r) => s + r[1], 0),
    seconds: 180 + max * 3,
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: {
      kind: "written",
      limit: { min: Math.floor(max * 0.5), max, unit: "字" },
      model,
      rubric: rubric.map(([label, p, keywords]) => ({ label, points: p, keywords })),
    },
    point,
    steps: steps(st),
  };
}

