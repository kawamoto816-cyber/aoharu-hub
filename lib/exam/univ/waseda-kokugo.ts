/** 4択。options の先頭が正解（画面では並べかえる） */
function ch(id: string, d: 1 | 2 | 3, unit: string, prompt: string, options: string[], why: string[], point: string, st: St, base = 70): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: sec(d, base),
    skill: d === 1 ? "知識・技能" : "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "choice", options, correct: 0, why },
    point,
    steps: steps(st),
  };
}

/** 漢字の書き取り（本文ではカタカナ） */
function kj(id: string, d: 1 | 2, label: string, kata: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: 40,
    skill: "知識・技能",
    unit: KANJI,
    prompt: `傍線部（${label}）のカタカナ「${kata}」を漢字に改めよ（送り仮名が必要なものはひらがなで添えること）。`,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

/** 本文からの抜き出し */
function nk(id: string, d: 1 | 2 | 3, unit: string, prompt: string, ans: string, point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: sec(d, 90),
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "term", accept: [ans], chars: [...ans].length },
    point,
    steps: steps(st),
  };
}

function S(n: number, id: string, unit: string, title: string, lead: string, body: string, questions: Question[], pick: number): ExamPoolSection {
  return {
    unit,
    tag: `${K}:${n}`,
    section: {
      id: `wk-${id}`,
      title,
      lead,
      style: "reading",
      examOnly: true,
      pick,
      material: [{ kind: "passage", lang: "ja", body }],
      questions,
    },
  };
}

