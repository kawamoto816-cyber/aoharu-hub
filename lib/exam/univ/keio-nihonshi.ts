const K: Skill = "知識・技能";
const T: Skill = "思考・判断・表現";
type D = 1 | 2 | 3;
type Step = [string, string];

const steps = (s: Step[]) => s.map(([title, body]) => ({ title, body }));

/** 4択 (opts は [選択肢, 理由]) */
function ch(id: string, unit: string, d: D, skill: Skill, prompt: string, opts: [string, string][], correct: number, point: string, st: Step[], keepOrder = false): Question {
  return {
    id,
    type: "B",
    unit,
    difficulty: d,
    points: 3 + d,
    seconds: 40 + d * 20,
    skill,
    prompt,
    answer: { kind: "choice", options: opts.map((o) => o[0]), correct, why: opts.map((o) => o[1]) },
    point,
    steps: steps(st),
    ...(keepOrder ? { keepOrder: true } : {}),
  };
}

/** 漢字の語句記述 */
function tm(id: string, unit: string, d: D, prompt: string, accept: string[], point: string, st: Step[]): Question {
  return {
    id,
    type: "B",
    unit,
    difficulty: d,
    points: 3 + d,
    seconds: 30 + d * 10,
    skill: K,
    prompt,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

/** 2文の正誤の組合せ */
function tf(id: string, unit: string, d: D, lead: string, x: string, y: string, xOk: boolean, yOk: boolean, whyX: string, whyY: string, point: string): Question {
  const combos: [boolean, boolean][] = [[true, true], [true, false], [false, true], [false, false]];
  const mark = (b: boolean) => (b ? "正" : "誤");
  const correct = combos.findIndex(([a, b]) => a === xOk && b === yOk);
  const opts: [string, string][] = combos.map(([a, b], i) => [
    `X ${mark(a)}　Y ${mark(b)}`,
    i === correct ? `正解。X は${mark(xOk)}（${whyX}）、Y は${mark(yOk)}（${whyY}）。` : `X は${mark(xOk)}、Y は${mark(yOk)}なので、この組合せは合わない。`,
  ]);
  return ch(id, unit, d, T, `${lead}\nX　${x}\nY　${y}`, opts, correct, point, [
    ["X を判定する", `${whyX}。よって X は{{${mark(xOk)}}}。`],
    ["Y を判定する", `${whyY}。よって Y は{{${mark(yOk)}}}。`],
  ], true);
}

/** 年代整序 (items は Ⅰ・Ⅱ・Ⅲ の文と年。order は正しい順の番号 [0..2]、wrong は誤りの順 3つ) */
function ord(id: string, unit: string, d: D, lead: string, items: [string, string][], order: number[], wrong: number[][], point: string): Question {
  const L = ["Ⅰ", "Ⅱ", "Ⅲ"];
  const seq = (o: number[]) => o.map((i) => L[i]).join("→");
  const right = order.map((i) => `${L[i]}（${items[i][1]}）`).join("→");
  const all = [order, ...wrong];
  const opts: [string, string][] = all.map((o, i) => [seq(o), i === 0 ? `正解。${right}。` : `誤り。正しい順は ${right}。`]);
  return ch(id, unit, d, T, `${lead}\n${items.map((it, i) => `${L[i]}　${it[0]}`).join("\n")}`, opts, 0, point, [
    ["それぞれの年代を思い出す", items.map((it, i) => `${L[i]} は${it[1]}`).join("、") + "。"],
    ["古い順に並べる", `{{${seq(order)}}} となる。`],
  ]);
}

