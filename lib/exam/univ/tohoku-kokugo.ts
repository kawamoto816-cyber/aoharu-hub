const steps = (s: St) => s.map(([title, body]) => ({ title, body }));
const sec = (d: D) => (d === 1 ? 50 : d === 2 ? 80 : 110);

/** 4択 (正解は options[0]。画面では並べかえる) */
function ch(id: string, d: D, unit: string, prompt: string, options: string[], why: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 3,
    seconds: sec(d),
    skill: d === 1 ? "知識・技能" : "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "choice", options, correct: 0, why },
    point,
    steps: steps(st),
  };
}

/** 漢字の書き取り */
function kj(id: string, d: D, prompt: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: 40,
    skill: "知識・技能",
    unit: KANJI,
    prompt,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

/** 漢文の読み (ひらがなで書く) */
function ym(id: string, d: D, unit: string, prompt: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: 40,
    skill: "知識・技能",
    unit,
    prompt,
    answer: { kind: "term", accept, script: "hira" },
    point,
    steps: steps(st),
  };
}

/** 記述 (type C・毎回出る。rubric の合計が配点。max は字数の上限) */
function wr(id: string, d: 2 | 3, unit: string, prompt: string, max: number, model: string, rubric: Rb, point: string, st: St): Question {
  return {
    id,
    type: "C",
    difficulty: d,
    points: rubric.reduce((s, r) => s + r[1], 0),
    seconds: 180 + max * 4,
    skill: "思考・判断・表現",
    unit,
    prompt: `${prompt}（${max}字以内）`,
    answer: {
      kind: "written",
      limit: { min: Math.floor(max * 0.6), max, unit: "字" },
      model,
      rubric: rubric.map(([label, p, keywords]) => ({ label, points: p, keywords })),
    },
    point,
    steps: steps(st),
  };
}

