const K: Skill = "知識・技能";
const T: Skill = "思考・判断・表現";
const P = { 1: 3, 2: 4, 3: 5 } as const;
const S = { 1: 45, 2: 70, 3: 95 } as const;
type St = [string, string][];
const steps = (st: St) => st.map(([title, body]) => ({ title, body }));

/** 4択 (opts は [選択肢, 理由]。c が正解の番号) */
function ch(a: { id: string; u: string; d: Difficulty; s?: Skill; p: string; o: [string, string][]; c?: number; pt: string; st: St; keep?: boolean }): QuestionB {
  return {
    id: a.id,
    type: "B",
    difficulty: a.d,
    points: P[a.d],
    seconds: S[a.d],
    skill: a.s ?? K,
    unit: a.u,
    prompt: a.p,
    ...(a.keep ? { keepOrder: true } : {}),
    answer: { kind: "choice", options: a.o.map((x) => x[0]), correct: a.c ?? 0, why: a.o.map((x) => x[1]) },
    point: a.pt,
    steps: steps(a.st),
  };
}

/** 2文の正誤の組合せ */
function sg(a: { id: string; u: string; d: Difficulty; p: string; a: [boolean, string]; b: [boolean, string]; pt: string; st: St }): QuestionB {
  const combos: [boolean, boolean][] = [[true, true], [true, false], [false, true], [false, false]];
  const mark = (x: boolean) => (x ? "正" : "誤");
  const c = combos.findIndex(([x, y]) => x === a.a[0] && y === a.b[0]);
  return ch({
    id: a.id,
    u: a.u,
    d: a.d,
    s: T,
    p: a.p,
    keep: true,
    c,
    o: combos.map(([x, y], i) => [
      `a ${mark(x)}　b ${mark(y)}`,
      i === c ? `正解。a は${mark(a.a[0])}（${a.a[1]}）、b は${mark(a.b[0])}（${a.b[1]}）。` : x !== a.a[0] ? `a は${mark(a.a[0])}。${a.a[1]}` : `b は${mark(a.b[0])}。${a.b[1]}`,
    ]),
    pt: a.pt,
    st: a.st,
  });
}

/** 語句の記述 */
function tm(a: { id: string; u: string; d: Difficulty; p: string; acc: string[]; pt: string; st: St; any?: boolean }): QuestionB {
  return {
    id: a.id,
    type: "B",
    difficulty: a.d,
    points: P[a.d],
    seconds: S[a.d],
    skill: K,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "term", accept: a.acc, script: a.any ? "any" : "kanji" },
    point: a.pt,
    steps: steps(a.st),
  };
}

/** 論述 (毎回出す) */
function wr(a: { id: string; u: string; p: string; lim: [number, number]; model: string; rub: { label: string; points: number; keywords?: string[] }[]; pt: string; st: St }): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: a.id,
    type: "C",
    difficulty: 3,
    points,
    seconds: a.lim[1] >= 300 ? 1200 : 900,
    skill: T,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", limit: { min: a.lim[0], max: a.lim[1], unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: steps(a.st),
  };
}

