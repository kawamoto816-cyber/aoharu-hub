const steps = (s: St) => s.map(([title, body]) => ({ title, body }));

/** 4択 (正解は options[0]。画面では並べかえる) */
function ch(id: string, d: D, unit: string, points: number, prompt: string, options: string[], why: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points,
    seconds: d === 1 ? 50 : d === 2 ? 80 : 110,
    skill: d === 1 ? "知識・技能" : "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "choice", options, correct: 0, why },
    point,
    steps: steps(st),
  };
}

/** 漢字の書き取り (本文ではカタカナ) */
function kj(id: string, d: D, mark: string, kana: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: 40,
    skill: "知識・技能",
    unit: KANJI,
    prompt: `傍線部${mark}「${kana}」を漢字に改めよ（楷書で書くこと）。`,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

/** 字数つきの記述 (type C・毎回出る。rubric の合計が配点) */
function wr(id: string, unit: string, d: D, prompt: string, max: number, model: string, rubric: Rub, point: string, st: St): Question {
  return {
    id,
    type: "C",
    difficulty: d,
    points: rubric.reduce((s, r) => s + r[1], 0),
    seconds: max >= 200 ? 1800 : max >= 120 ? 900 : max >= 80 ? 540 : 420,
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: {
      kind: "written",
      limit: { min: Math.round(max * 0.7), max, unit: "字" },
      model,
      rubric: rubric.map(([label, points, keywords]) => ({ label, points, keywords })),
    },
    point,
    steps: steps(st),
  };
}

