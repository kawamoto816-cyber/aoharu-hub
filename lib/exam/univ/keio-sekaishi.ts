type St = [string, string];
const steps = (s: St[]): SolutionStep[] => s.map(([title, body]) => ({ title, body }));
const K: Skill = "知識・技能";
const S: Skill = "思考・判断・表現";

/** 4択 */
function C(
  id: string,
  difficulty: 1 | 2 | 3,
  unit: string,
  prompt: string,
  options: string[],
  correct: number,
  why: string[],
  point: string,
  st: St[],
  skill: Skill = K,
): QuestionB {
  return { id, type: "B", difficulty, points: 4, seconds: 70 + 20 * difficulty, skill, unit, prompt, answer: { kind: "choice", options, correct, why }, point, steps: steps(st) };
}

/** 語句記述 */
function T(
  id: string,
  difficulty: 1 | 2 | 3,
  unit: string,
  prompt: string,
  accept: string[],
  script: "kanji" | "any",
  point: string,
  st: St[],
  near?: { text: string; why: string }[],
): QuestionB {
  return { id, type: "B", difficulty, points: 3, seconds: 60, skill: K, unit, prompt, answer: { kind: "term", accept, script, ...(near ? { near } : {}) }, point, steps: steps(st) };
}

/** 短い論述 */
function R(
  id: string,
  difficulty: 1 | 2 | 3,
  unit: string,
  prompt: string,
  max: number,
  model: string,
  rubric: [string, number, string[]][],
  point: string,
  st: St[],
): QuestionB {
  const points = rubric.reduce((s, r) => s + r[1], 0);
  return {
    id,
    type: "B",
    difficulty,
    points,
    seconds: 300,
    skill: S,
    unit,
    prompt,
    answer: { kind: "written", limit: { max, unit: "字" }, model, rubric: rubric.map(([label, p, keywords]) => ({ label, points: p, keywords })) },
    point,
    steps: steps(st),
  };
}

const PICK = 9;
function sec(tag: number, id: string, unit: string, title: string, body: string, questions: QuestionB[]): ExamPoolSection {
  return {
    unit,
    tag: `keio-sekaishi:${tag}`,
    section: {
      id: `keio-sw-${id}`,
      title,
      lead: "次の文章を読み、下線部・空欄に関する問いに答えよ。",
      style: "reading",
      examOnly: true,
      material: [{ kind: "passage", lang: "ja", body }],
      pick: PICK,
      questions,
    },
  };
}

