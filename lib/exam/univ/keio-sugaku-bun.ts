// 形式: 80分・大問6題・150点。前半の第1〜3問は答えの数だけを空所に入れる形 (マーク)、後半の第4〜6問は途中の過程も書く記述式。
//   範囲は数学Ⅰ・Ⅱ・A・B（数列）・C（ベクトル）。確率・数列・整数・微分積分・ベクトルがよく出る。
// 問題はすべてこの型のために書き下ろしたもの (過去問の文・数値・設定は使っていない)。答えの数値は sympy で検算した。
// 参考:
//   https://www.keio.ac.jp/ja/admissions/docs/240419_generaladmissions2025.pdf (慶應義塾大学 一般選抜要項: 経済学部A方式 数学 80分・150点)
//   https://study-search.jp/columns/247 (慶應経済 数学の傾向: 大問6題・前半3題はマーク・後半3題は記述)
//   https://www.toshin.com/nakameguro/?p=26894 (慶應経済入試情報: 確率・数列・微積分が頻出)

const KEY = "keio-sugaku-bun";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD1 = "次の文中の空欄にあてはまる数を答えよ。答えのみを記入せよ。";
const LEAD2 = "次の問いに答えよ。解答は答えだけでなく、途中の過程も記述せよ。";

type St = ([string, string] | [string, string, string])[];
type Rub = { label: string; points: number; keywords?: string[] }[];
const steps = (st: St) => st.map(([title, body, trap]) => (trap ? { title, body, trap } : { title, body }));
const PTS: Record<Difficulty, number> = { 1: 7, 2: 8, 3: 10 };

interface N {
  id: string;
  u: string;
  d: Difficulty;
  p: string;
  a: Omit<NumQ, "kind">;
  dep?: string;
  pt: string;
  st: St;
}
/** 空所補充の1問 (答えのみ・自動採点) */
function nm(q: N): QuestionC {
  return {
    id: q.id,
    type: "C",
    difficulty: q.d,
    points: PTS[q.d],
    seconds: q.d === 3 ? 480 : 300,
    skill: "知識・技能",
    unit: q.u,
    ...(q.dep ? { dependsOn: q.dep } : {}),
    prompt: q.p,
    answer: { kind: "num", ...q.a },
    point: q.pt,
    steps: steps(q.st),
  };
}

interface W {
  id: string;
  u: string;
  d: Difficulty;
  p: string;
  model: string;
  rub: Rub;
  auto?: Omit<NumQ, "kind">;
  dep?: string;
  pt: string;
  st: St;
}
/** 記述の1問 (模範解答と採点基準で自己採点。最後の数値は autoPart) */
function wr(q: W): QuestionC {
  const points = q.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: q.id,
    type: "C",
    difficulty: q.d,
    points,
    seconds: q.d === 3 ? 720 : 480,
    skill: "思考・判断・表現",
    unit: q.u,
    ...(q.dep ? { dependsOn: q.dep } : {}),
    prompt: q.p,
    answer: { kind: "written", model: q.model, rubric: q.rub, ...(q.auto ? { autoPart: { kind: "num", ...q.auto } } : {}) },
    point: q.pt,
    steps: steps(q.st),
  };
}

function sec(tag: number, id: string, unit: string, title: string, lead: string, body: string, qs: QuestionC[]): ExamPoolSection {
  return {
    unit,
    tag: TAG(tag),
    section: {
      id: `keio-sugaku-${tag}-${id}`,
      title,
      lead,
      material: [{ kind: "text" as const, body }],
      questions: qs,
    },
  };
}

