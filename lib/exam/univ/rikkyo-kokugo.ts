type D = 1 | 2 | 3;
type St = [string, string][];

const steps = (s: St) => s.map(([title, body]) => ({ title, body }));
const sec = (d: D) => (d === 1 ? 40 : d === 2 ? 70 : 100);
const pts = (d: D) => (d === 1 ? 6 : d === 2 ? 8 : 10);

/** 4択 */
function ch(id: string, d: D, unit: string, prompt: string, options: string[], correct: number, why: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: sec(d),
    skill: d === 1 ? "知識・技能" : "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "choice", options, correct, why },
    point,
    steps: steps(st),
  };
}

/** 漢字の書き取り (本文ではカタカナ) */
function kj(id: string, d: D, mark: string, kana: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: 30,
    skill: "知識・技能",
    unit: KJ,
    prompt: `傍線部${mark}のカタカナ「${kana}」を漢字に改めよ。`,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

/** 抜き出し */
function nk(id: string, d: D, unit: string, prompt: string, chars: number, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: sec(d) + 30,
    skill: "思考・判断・表現",
    unit,
    prompt: `${prompt}本文中から${chars}字で抜き出せ（句読点は含まない）。`,
    answer: { kind: "term", accept, chars },
    point,
    steps: steps(st),
  };
}

/** 記述・現代語訳 (毎回出す) */
function wr(id: string, unit: string, prompt: string, max: number, model: string, rubric: [string, number, string[]?][], point: string, st: St): Question {
  const total = rubric.reduce((s, r) => s + r[1], 0);
  return {
    id,
    type: "C",
    difficulty: 3,
    points: total,
    seconds: 300,
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: {
      kind: "written",
      limit: { max, unit: "字" },
      model,
      rubric: rubric.map(([label, points, keywords]) => ({ label, points, ...(keywords ? { keywords } : {}) })),
    },
    point,
    steps: steps(st),
  };
}

function S(n: number, id: string, unit: string, title: string, lead: string, body: string, pick: number, questions: Question[], ptitle?: string): ExamPoolSection {
  return {
    unit,
    tag: `${K}:${n}`,
    section: {
      id: `rk-${id}`,
      title,
      lead,
      style: "reading",
      examOnly: true,
      pick,
      material: [{ kind: "passage", lang: "ja", ...(ptitle ? { title: ptitle } : {}), body }],
      questions,
    },
  };
}

