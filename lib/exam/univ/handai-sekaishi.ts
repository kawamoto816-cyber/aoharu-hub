const K: Skill = "知識・技能";
const T: Skill = "思考・判断・表現";
const P = { 1: 4, 2: 5, 3: 6 } as const;
const S = { 1: 50, 2: 75, 3: 100 } as const;
type St = [string, string][];
const steps = (st: St) => st.map(([title, body]) => ({ title, body }));

/** 4択 (o は [選択肢, 理由]。c が正解の番号) */
function ch(a: { id: string; u: string; d: Difficulty; s?: Skill; p: string; o: [string, string][]; c?: number; pt: string; st: St }): QuestionB {
  return {
    id: a.id,
    type: "B",
    difficulty: a.d,
    points: P[a.d],
    seconds: S[a.d],
    skill: a.s ?? K,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "choice", options: a.o.map((x) => x[0]), correct: a.c ?? 0, why: a.o.map((x) => x[1]) },
    point: a.pt,
    steps: steps(a.st),
  };
}

/** 語句の記述 (any=カタカナなどで答える語) */
function tm(a: { id: string; u: string; d: Difficulty; p: string; acc: string[]; pt: string; st: St; any?: boolean }): QuestionB {
  return {
    id: a.id,
    type: "B",
    difficulty: a.d,
    points: P[a.d],
    seconds: S[a.d],
    skill: K,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "term", accept: a.acc, script: a.any ? "any" : "kanji" },
    point: a.pt,
    steps: steps(a.st),
  };
}

/** 論述 (毎回出す。節の最後に置く) */
function wr(a: { u: string; p: string; lim: [number, number]; model: string; rub: { label: string; points: number; keywords?: string[] }[]; pt: string; st: St }): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: "ronjutsu",
    type: "C",
    difficulty: 3,
    points,
    seconds: a.lim[1] >= 300 ? 1500 : a.lim[1] >= 150 ? 900 : 600,
    skill: T,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", limit: { min: a.lim[0], max: a.lim[1], unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: steps(a.st),
  };
}

