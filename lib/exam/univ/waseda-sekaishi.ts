type St = [string, string][];
const st = (s: St) => s.map(([title, body]) => ({ title, body }));

/** 4択 (誤り・正しいもの・組合せ) */
function C(id: string, d: Difficulty, unit: string, prompt: string, options: string[], correct: number, why: string[], point: string, steps: St, keepOrder = false): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: d === 3 ? 90 : 70,
    skill: d === 3 ? "思考・判断・表現" : "知識・技能",
    unit,
    prompt,
    answer: { kind: "choice", options, correct, why },
    point,
    steps: st(steps),
    ...(keepOrder ? { keepOrder: true } : {}),
  };
}

/** 語句記述 */
function T(id: string, d: Difficulty, unit: string, prompt: string, accept: string[], point: string, steps: St, script: "kanji" | "any" = "kanji"): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: 2,
    seconds: 50,
    skill: "知識・技能",
    unit,
    prompt,
    answer: { kind: "term", accept, script },
    point,
    steps: st(steps),
  };
}

const TF = ["a 正　b 正", "a 正　b 誤", "a 誤　b 正", "a 誤　b 誤"];
/** 2文の正誤の組合せ */
function TF2(id: string, d: Difficulty, unit: string, a: string, aOk: boolean, aWhy: string, b: string, bOk: boolean, bWhy: string, point: string, steps: St): Question {
  const correct = (aOk ? 0 : 2) + (bOk ? 0 : 1);
  const why = TF.map((_, i) => {
    const oa = i < 2;
    const ob = i % 2 === 0;
    const miss: string[] = [];
    if (oa !== aOk) miss.push(`a は${aOk ? "正しい" : "誤り"}`);
    if (ob !== bOk) miss.push(`b は${bOk ? "正しい" : "誤り"}`);
    return i === correct ? `正解。a：${aWhy}　b：${bWhy}` : `${miss.join("、")}。a：${aWhy}　b：${bWhy}`;
  });
  return C(id, d, unit, `次の文a・bの正誤の組合せとして正しいものを1つ選べ。\na　${a}\nb　${b}`, TF, correct, why, point, steps, true);
}

/** 年代整序 (a・b・c を古い順に) */
function ORD(id: string, d: Difficulty, unit: string, items: [string, string, string], seqs: string[], correct: number, dates: string, point: string): Question {
  const why = seqs.map((s, i) => (i === correct ? `正解。${dates}` : `正しい順は ${seqs[correct]}。${dates}`));
  return C(
    id,
    d,
    unit,
    `次のできごとa〜cを、古いものから年代順に正しく並べたものを1つ選べ。\na　${items[0]}\nb　${items[1]}\nc　${items[2]}`,
    seqs,
    correct,
    why,
    point,
    [
      ["それぞれの年代を思い出す", dates],
      ["順に並べる", `古い順は {{${seqs[correct]}}}。`],
    ],
    true,
  );
}

