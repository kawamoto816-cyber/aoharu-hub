const KEY = "aoyama-sugaku-bun";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD_M = "次の各問の空欄にあてはまる数または式を答えよ。（マーク式にあたる。答えのみ記入）";
const LEAD_W = "次の問いに答えよ。解答は答えだけでなく、途中の過程も記述せよ。";

type St = ([string, string] | [string, string, string])[];
type Rub = { label: string; points: number; keywords?: string[] }[];
const steps = (st: St) => st.map(([title, body, trap]) => (trap ? { title, body, trap } : { title, body }));

interface N {
  id: string;
  u: string;
  d: Difficulty;
  p: string;
  a: Omit<NumQ, "kind">;
  dep?: string;
  pts?: number;
  sec?: number;
  pt: string;
  st: St;
}
/** マーク式の1問 (答えのみ・自動採点) */
function nm(q: N): QuestionC {
  return {
    id: q.id,
    type: "C",
    difficulty: q.d,
    points: q.pts ?? 10,
    seconds: q.sec ?? 300,
    skill: "知識・技能",
    unit: q.u,
    ...(q.dep ? { dependsOn: q.dep } : {}),
    prompt: q.p,
    answer: { kind: "num", ...q.a },
    point: q.pt,
    steps: steps(q.st),
  };
}
/** 小問集合の1問 (6点・4分) */
const sq = (q: Omit<N, "pts" | "sec">) => nm({ ...q, pts: 6, sec: 240 });

interface W {
  id: string;
  u: string;
  d: Difficulty;
  p: string;
  model: string;
  rub: Rub;
  auto?: Omit<NumQ, "kind">;
  dep?: string;
  sec?: number;
  pt: string;
  st: St;
}
/** 記述の1問 (模範解答と採点基準で自己採点。最後の数値は autoPart) */
function wr(q: W): QuestionC {
  const points = q.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: q.id,
    type: "C",
    difficulty: q.d,
    points,
    seconds: q.sec ?? 400,
    skill: "思考・判断・表現",
    unit: q.u,
    ...(q.dep ? { dependsOn: q.dep } : {}),
    prompt: q.p,
    answer: { kind: "written", model: q.model, rubric: q.rub, ...(q.auto ? { autoPart: { kind: "num", ...q.auto } } : {}) },
    point: q.pt,
    steps: steps(q.st),
  };
}

function sec(tag: number, id: string, unit: string, title: string, lead: string, qs: QuestionC[], body?: string): ExamPoolSection {
  return {
    unit,
    tag: TAG(tag),
    section: {
      id: `aoyama-sugaku-${tag}-${id}`,
      title,
      lead,
      ...(body ? { material: [{ kind: "text" as const, body }] } : {}),
      questions: qs,
    },
  };
}

