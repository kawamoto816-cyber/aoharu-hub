/** 記述 (type C・毎回出る。rubric の合計が配点) */
function wr(id: string, unit: string, prompt: string, max: number, model: string, rubric: Rb, point: string, st: St): Question {
  return {
    id,
    type: "C",
    difficulty: 3,
    points: rubric.reduce((s, r) => s + r[1], 0),
    seconds: 240 + max * 3,
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "written", limit: { max, unit: "字" }, model, rubric: rubric.map(([label, p, keywords]) => ({ label, points: p, keywords })) },
    point,
    steps: steps(st),
  };
}

