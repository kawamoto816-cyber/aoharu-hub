const steps = (s: St) => s.map(([title, body]) => ({ title, body }));

/** 説明・現代語訳 (type B の記述。pick で入れかえる)。字数の下限は上限の7割 (訳は下限なし) */
function wb(id: string, d: D, unit: string, prompt: string, max: number, model: string, rub: Rub, point: string, st: St, noMin = false): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: rub.reduce((s, r) => s + r[1], 0),
    seconds: max >= 60 ? (d === 3 ? 480 : 420) : 180,
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: {
      kind: "written",
      limit: noMin ? { max, unit: "字" } : { min: Math.round(max * 0.7), max, unit: "字" },
      model,
      rubric: rub.map(([label, points, keywords]) => ({ label, points, keywords })),
    },
    point,
    steps: steps(st),
  };
}

/** 100字以上120字以内の説明 (type C・毎回出る) */
function wc(id: string, prompt: string, model: string, rub: Rub, point: string, st: St): Question {
  return {
    id,
    type: "C",
    difficulty: 3,
    points: rub.reduce((s, r) => s + r[1], 0),
    seconds: 900,
    skill: "思考・判断・表現",
    unit: YOYAKU,
    prompt,
    answer: {
      kind: "written",
      limit: { min: 100, max: 120, unit: "字" },
      model,
      rubric: rub.map(([label, points, keywords]) => ({ label, points, keywords })),
    },
    point,
    steps: steps(st),
  };
}

/** 漢字の書き取り (type B・難しさ1) */
function kj(id: string, prompt: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: 1,
    points: 2,
    seconds: 40,
    skill: "知識・技能",
    unit: KANJI,
    prompt,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

