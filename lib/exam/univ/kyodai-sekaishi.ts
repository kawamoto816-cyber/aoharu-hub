const K: Skill = "知識・技能";
const T: Skill = "思考・判断・表現";
const P = { 1: 2, 2: 3, 3: 4 } as const;
const S = { 1: 40, 2: 55, 3: 75 } as const;
type St = [string, string][];
const steps = (st: St) => st.map(([title, body]) => ({ title, body }));

/** 語句の記述 (any=カタカナ可) */
function tm(a: { id: string; u: string; d: Difficulty; p: string; acc: string[]; pt: string; st: St; any?: boolean }): QuestionB {
  return {
    id: a.id,
    type: "B",
    difficulty: a.d,
    points: P[a.d],
    seconds: S[a.d],
    skill: K,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "term", accept: a.acc, script: a.any ? "any" : "kanji" },
    point: a.pt,
    steps: steps(a.st),
  };
}

/** 短い論述 (語句記述の大問の中。プールから選ぶ) */
function sw(a: { id: string; u: string; p: string; max: number; model: string; rub: { label: string; points: number; keywords?: string[] }[]; pt: string; st: St }): QuestionB {
  return {
    id: a.id,
    type: "B",
    difficulty: 3,
    points: a.rub.reduce((x, r) => x + r.points, 0),
    seconds: 150,
    skill: T,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", limit: { max: a.max, unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: steps(a.st),
  };
}

/** 300字論述 (毎回出す) */
function wr(a: { id: string; u: string; p: string; model: string; rub: { label: string; points: number; keywords?: string[] }[]; pt: string; st: St }): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: a.id,
    type: "C",
    difficulty: 3,
    points,
    seconds: 1500,
    skill: T,
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", limit: { min: 250, max: 300, unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: steps(a.st),
  };
}

