const steps = (s: St) => s.map(([title, body]) => ({ title, body }));
const sec = (d: 1 | 2 | 3) => (d === 1 ? 40 : d === 2 ? 70 : 100);
const pts = (d: 1 | 2 | 3) => (d === 1 ? 3 : d === 2 ? 4 : 5);

/** 4択 (正解は options[0]。画面で並べかえる) */
function ch(id: string, d: 1 | 2 | 3, unit: string, prompt: string, options: string[], why: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: sec(d),
    skill: d === 1 ? "知識・技能" : "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "choice", options, correct: 0, why },
    point,
    steps: steps(st),
  };
}

/** 漢字の書き取り */
function kj(id: string, d: 1 | 2 | 3, prompt: string, accept: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: 30,
    skill: "知識・技能",
    unit: KANJI,
    prompt,
    answer: { kind: "term", accept, script: "kanji" },
    point,
    steps: steps(st),
  };
}

/** 抜き出し */
function nk(id: string, d: 1 | 2 | 3, unit: string, prompt: string, accept: string[], chars: number, point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: 90,
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "term", accept, script: "any", chars },
    point,
    steps: steps(st),
  };
}

/** 50字以内の記述 */
function wr(id: string, prompt: string, model: string, rubric: { label: string; points: number; keywords?: string[] }[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: 3,
    points: rubric.reduce((x, r) => x + r.points, 0),
    seconds: 300,
    skill: "思考・判断・表現",
    unit: RON,
    prompt,
    answer: { kind: "written", limit: { max: 50, unit: "字" }, model, rubric },
    point,
    steps: steps(st),
  };
}

function S(n: number, id: string, unit: string, title: string, lead: string, body: string, pick: number, questions: Question[], ptitle?: string): ExamPoolSection {
  return {
    unit,
    tag: `${K}:${n}`,
    section: {
      id: `mjk-${id}`,
      title,
      lead,
      style: "reading",
      examOnly: true,
      pick,
      material: [{ kind: "passage", lang: "ja", title: ptitle, body }],
      questions,
    },
  };
}

