//   https://jyuke-labo.com/daigakujyukentaisaku/toukyoudaigaku/nihonshi/ (東大日本史の傾向: 大問4題・資料文を読む論述)
//   https://study-search.jp/columns/302 (東大日本史の出題形式と字数)

const KEY = "todai-nihonshi";
const TAG = (i: number) => `${KEY}:${i}`;
const LEAD = "次の文章（資料文）を読み、下の設問A・Bに答えよ。解答は指定の字数以内で書け。";

type St = [string, string][];
type Rub = { label: string; points: number; keywords?: string[] }[];
interface W {
  id: string;
  u: string;
  d?: Difficulty;
  p: string;
  /** 字数の上限 (下限はその8割) */
  max: number;
  model: string;
  rub: Rub;
  pt: string;
  st: St;
}

function wr(a: W): QuestionC {
  const points = a.rub.reduce((x, r) => x + r.points, 0);
  return {
    id: a.id,
    type: "C",
    difficulty: a.d ?? (a.max >= 120 ? 3 : 2),
    points,
    seconds: a.max >= 120 ? 600 : 360,
    skill: "思考・判断・表現",
    unit: a.u,
    prompt: a.p,
    answer: { kind: "written", limit: { min: Math.round(a.max * 0.8), max: a.max, unit: "字" }, model: a.model, rubric: a.rub },
    point: a.pt,
    steps: a.st.map(([title, body]) => ({ title, body })),
  };
}

function sec(tag: number, id: string, unit: string, title: string, body: string[], qs: QuestionC[]): ExamPoolSection {
  return {
    unit,
    tag: TAG(tag),
    section: {
      id: `todai-nihon-${tag}-${id}`,
      title,
      lead: LEAD,
      material: [{ kind: "passage", lang: "ja", body: body.join("\n") }],
      questions: qs,
    },
  };
}

