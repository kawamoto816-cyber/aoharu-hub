const K = "chuo-nihonshi";
type St = [string, string][];

const steps = (s: St) => s.map(([title, body]) => ({ title, body }));
const sec = (d: 1 | 2 | 3) => (d === 1 ? 40 : d === 2 ? 55 : 75);
const pts = (d: 1 | 2 | 3) => (d === 3 ? 4 : 3);

/** 4択 */
function ch(id: string, d: 1 | 2 | 3, unit: string, prompt: string, options: string[], correct: number, why: string[], point: string, st: St): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: sec(d),
    skill: d === 3 ? "思考・判断・表現" : "知識・技能",
    unit,
    prompt,
    answer: { kind: "choice", options, correct, why },
    point,
    steps: steps(st),
  };
}

/** 2文の正誤の組合せ */
function sei(id: string, d: 1 | 2 | 3, unit: string, lead: string, x: string, y: string, xOk: boolean, yOk: boolean, whyX: string, whyY: string, point: string, st: St): Question {
  const opts = ["X 正　Y 正", "X 正　Y 誤", "X 誤　Y 正", "X 誤　Y 誤"];
  const correct = (xOk ? 0 : 2) + (yOk ? 0 : 1);
  const why = opts.map((_, i) => {
    const ox = i < 2, oy = i % 2 === 0;
    const head = i === correct ? "正しい組合せ。" : `誤り。X は${xOk ? "正" : "誤"}、Y は${yOk ? "正" : "誤"}。`;
    return `${head}${ox !== xOk || i === correct ? `X: ${whyX}` : ""}${oy !== yOk || i === correct ? ` Y: ${whyY}` : ""}`.trim();
  });
  return {
    id,
    type: "B",
    keepOrder: true,
    difficulty: d,
    points: pts(d),
    seconds: 80,
    skill: "思考・判断・表現",
    unit,
    prompt: `${lead}について述べた次の文X・Yの正誤の組合せとして正しいものを選べ。\nX　${x}\nY　${y}`,
    answer: { kind: "choice", options: opts, correct, why },
    point,
    steps: steps(st),
  };
}

/** 年代の古い順 (items は問題に出す順 Ⅰ・Ⅱ・Ⅲ、order は正しい順の番号、years はそれぞれの年代) */
function nen(id: string, d: 1 | 2 | 3, unit: string, lead: string, items: [string, string, string], years: [string, string, string], order: [number, number, number], point: string, st: St): Question {
  const R = ["Ⅰ", "Ⅱ", "Ⅲ"];
  const perms: [number, number, number][] = [[0, 1, 2], [0, 2, 1], [1, 0, 2], [1, 2, 0], [2, 0, 1], [2, 1, 0]];
  const opts = perms.map((p) => p.map((k) => R[k]).join("→"));
  const correct = perms.findIndex((p) => p.join() === order.join());
  const right = order.map((k) => `${R[k]}（${years[k]}）`).join("→");
  return {
    id,
    type: "B",
    keepOrder: true,
    difficulty: d,
    points: pts(d),
    seconds: 70,
    skill: "思考・判断・表現",
    unit,
    prompt: `${lead}次のⅠ〜Ⅲを年代の古い順に正しく並べたものを選べ。\nⅠ　${items[0]}\nⅡ　${items[1]}\nⅢ　${items[2]}`,
    answer: { kind: "choice", options: opts, correct, why: opts.map((_, i) => (i === correct ? `正しい。${right}。` : `誤り。正しくは ${right}。`)) },
    point,
    steps: steps(st),
  };
}

/** 漢字で書く語句 (カタカナの答えは script "any") */
function tm(id: string, d: 1 | 2 | 3, unit: string, prompt: string, accept: string[], point: string, st: St, script: "kanji" | "any" = "kanji"): Question {
  return {
    id,
    type: "B",
    difficulty: d,
    points: pts(d),
    seconds: 40,
    skill: "知識・技能",
    unit,
    prompt,
    answer: { kind: "term", accept, script },
    point,
    steps: steps(st),
  };
}

function S(n: number, id: string, unit: string, title: string, body: string, questions: Question[]): ExamPoolSection {
  return {
    unit,
    tag: `${K}:${n}`,
    section: {
      id: `cn-${id}`,
      title,
      lead: "次の文章を読み、問いに答えよ。",
      style: "reading",
      examOnly: true,
      pick: 6,
      material: [{ kind: "passage", lang: "ja", body }],
      questions,
    },
  };
}

