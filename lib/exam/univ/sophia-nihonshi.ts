const KEY = "sophia-nihonshi";
const TWO = ["X 正　Y 正", "X 正　Y 誤", "X 誤　Y 正", "X 誤　Y 誤"];

type Steps = [string, string][];
const st = (s: Steps) => s.map(([title, body]) => ({ title, body }));

/** 4択 */
const ch = (options: string[], correct: number, why: string[]): Answer => ({ kind: "choice", options, correct, why });
/** 漢字で書く語句 */
const tm = (...accept: string[]): Answer => ({ kind: "term", accept, script: "kanji" });

/** B の小問 (配点4・知識は130秒・語句は80秒) */
function b(id: string, difficulty: 1 | 2 | 3, unit: string, prompt: string, answer: Answer, point: string, steps: Steps, keepOrder = false): QuestionB {
  return {
    id,
    type: "B",
    difficulty,
    points: 4,
    seconds: answer.kind === "term" ? 80 : 130,
    skill: difficulty === 3 || keepOrder ? "思考・判断・表現" : "知識・技能",
    unit,
    prompt,
    answer,
    point,
    steps: st(steps),
    ...(keepOrder ? { keepOrder: true } : {}),
  };
}

/** 論述 (C。毎回出る) */
function w(
  id: string,
  unit: string,
  max: number,
  points: number,
  prompt: string,
  model: string,
  rubric: { label: string; points: number; keywords?: string[] }[],
  point: string,
  steps: Steps,
): QuestionC {
  return {
    id,
    type: "C",
    difficulty: 3,
    points,
    seconds: max <= 50 ? 300 : 900,
    skill: "思考・判断・表現",
    unit,
    prompt,
    answer: { kind: "written", limit: { max, unit: "字" }, model, rubric },
    point,
    steps: st(steps),
  };
}

