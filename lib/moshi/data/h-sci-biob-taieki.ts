const SANSO: [number, number][] = [];
for (let a = 90; a <= 100; a++) for (let c = 20; c <= 60; c += 2) {
  const x = ((a - c) / a) * 100;
  if (Number.isInteger(x)) SANSO.push([a, c]);
}

function sanso(r: Rng): QuestionBody {
  // 肺が 100％ の組は差がそのまま答えになるので、100％ でない組を多めに出す
  const not100 = r.bool(0.7);
  const [a, c] = r.pick(SANSO.filter(([x]) => (x !== 100) === not100));
  const ans = ((a - c) / a) * 100;
  return {
    prompt: `肺では、ヘモグロビンの ${a}％ が酸素ヘモグロビンになっていました。ある組織では、それが ${c}％ でした。肺で酸素と結合していたヘモグロビンのうち、何％ がこの組織で酸素を離しましたか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(ans)], unit: "％", calc: `(${a}-${c})/${a}*100` },
    point: "分母は肺で結合していた量",
    steps: [
      { title: "離した量", body: `${a} − ${c} ＝ ${a - c}（％ぶん）が組織で酸素を離した。`, back: [S4] },
      { title: "割合にする", body: `肺で結合していた ${a} に対する割合なので、${a - c} ÷ ${a} × 100 ＝ {{${ans}％}}。`, trap: a === 100 ? "肺が 100％ でないときは、差をそのまま答えにせず、肺での割合でわる。" : `${a - c}％ を答えにしない。「肺で結合していたうちの」割合なので ${a} でわる。` },
    ],
  };
}

function inulin(r: Rng): QuestionBody {
  const p = r.pick([0.1, 0.2]);
  const k = r.pick([100, 110, 120, 125, 130]);
  const perMin = r.bool();
  const V = perMin ? r.pick([1, 1.2, 1.5]) : r.pick([1.2, 1.4, 1.5, 1.6]);
  const uc = f(p * k);
  const ans = f(V * k);
  const [vu, au] = perMin ? ["1分間に " + V + " mL", "mL"] : ["1日に " + V + " L", "L"];
  return {
    prompt: `イヌリンを注射したあと、血しょう中のイヌリン濃度は ${f(p)} mg/mL、尿中のイヌリン濃度は ${uc} mg/mL でした。尿が${vu}できたとき、${perMin ? "1分間" : "1日"}にできた原尿の量は何 ${au} ですか。イヌリンは糸球体でこし出されたあと、まったく再吸収されないものとします。`,
    answer: { kind: "num", answerKind: "num", answer: [ans], unit: au, calc: `${V}*${uc}/${f(p)}` },
    point: "原尿の量＝尿量×濃縮率",
    steps: [
      { title: "濃縮率", body: `${uc} ÷ ${f(p)} ＝ {{${k} 倍}}。イヌリンは再吸収されないので、水だけが再吸収されて濃くなった。`, back: [S7] },
      { title: "原尿の量", body: `${V} ${au} × ${k} ＝ {{${ans} ${au}}}。`, trap: "濃縮率でわらない。尿は原尿が水を取りもどされて小さくなったものなので、原尿は尿より多い。" },
    ],
  };
}

