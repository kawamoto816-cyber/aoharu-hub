const f = (x: number) => String(Math.round(x * 1000) / 1000).replace("-", "−");
const fc = (x: number) => String(Math.round(x * 1000) / 1000);

function kion(r: Rng): QuestionBody {
  const low = r.step(100, 1500, 100);
  const diff = r.step(800, 3500, 100);
  const high = low + diff;
  const t0 = r.int(8, 30);
  const ans = Math.round((t0 - (diff / 100) * 0.6) * 10) / 10;
  const drop = Math.round((diff / 100) * 0.6 * 10) / 10;
  const place = r.pick(["ある山のふもと", "ある高原のふもとの町", "ある谷あいの村"]);
  return {
    prompt: `${place}（標高 ${low}m）の気温が ${t0}℃ のとき、同じ時刻の、標高 ${high}m の山頂の気温は約何℃ですか。気温は標高が100m上がるごとに0.6℃下がるものとして答えなさい。`,
    answer: { kind: "num", answerKind: "num", answer: [fc(ans)], unit: "℃", labels: ["約"], calc: `${t0}-(${high}-${low})/100*0.6` },
    point: "100m につき約0.6℃下がる",
    steps: [
      { title: "標高差を出す", body: `${high}−${low}＝${diff}（m）。100m の{{${diff / 100}倍}}です。`, back: [S1] },
      { title: "下がる気温を引く", body: `0.6×${diff / 100}＝${f(drop)}（℃）下がるので、${t0}−${f(drop)}＝{{${f(ans)}}}（℃）です。`, trap: "標高そのもの（山頂の標高）で計算しない。ふもととの標高差を使います。", back: [S1] },
    ],
  };
}

const ZONES = ["A（熱帯）", "C（温帯）", "D（亜寒帯〈冷帯〉）", "E（寒帯）"] as const;

function keppen(r: Rng): QuestionBody {
  const z = r.int(0, 3);
  let cold = 0;
  let warm = 0;
  if (z === 0) {
    cold = r.int(19, 26);
    warm = cold + r.int(1, 4);
  } else if (z === 1) {
    cold = r.int(-2, 16);
    warm = Math.min(30, cold + r.int(8, 20));
  } else if (z === 2) {
    cold = r.int(-38, -5);
    warm = r.int(11, 21);
  } else {
    warm = r.int(-20, 9);
    cold = warm - r.int(15, 30);
  }
  const why = [
    z === 0 ? "最寒月の平均気温が18℃以上なので熱帯。" : `熱帯は最寒月の平均気温が18℃以上。この地点の最寒月は${f(cold)}℃。`,
    z === 1 ? "最寒月の平均気温が−3℃以上18℃未満なので温帯。" : `温帯は最寒月が−3℃以上18℃未満。この地点は${z === 0 ? "最寒月が18℃以上" : z === 2 ? "最寒月が−3℃未満" : "最暖月が10℃未満で樹木が育たない"}。`,
    z === 2 ? "最暖月が10℃以上で樹木が育ち、最寒月が−3℃未満なので亜寒帯。" : `亜寒帯は最暖月10℃以上・最寒月−3℃未満。この地点は${z === 3 ? "最暖月が10℃未満" : "最寒月が−3℃以上"}。`,
    z === 3 ? "最暖月の平均気温が10℃未満で、樹木が育たないので寒帯。" : `寒帯は最暖月の平均気温が10℃未満。この地点の最暖月は${f(warm)}℃。`,
  ];
  const name = r.pick(["地点X", "地点Y", "地点Z", "観測地点P"]);
  return {
    prompt: `${name}の、最も暖かい月の平均気温は ${f(warm)}℃、最も寒い月の平均気温は ${f(cold)}℃ です。降水量は十分にあり、乾燥帯（B）にはあたりません。ケッペンの気候区分で、${name}はどの気候帯にあたりますか。`,
    answer: { kind: "choice", options: [...ZONES], correct: z, why },
    point: z === 3 ? "寒帯は最暖月10℃未満で決まる" : "樹木気候は最寒月の気温で分ける",
    steps: [
      { title: "まず樹木が育つか", body: `最暖月が10℃未満なら寒帯（E）。この地点は最暖月 ${f(warm)}℃ なので${z === 3 ? "{{寒帯}}です。" : "樹木が育つ気候です。"}`, back: [S4] },
      ...(z === 3
        ? []
        : [{ title: "最寒月で分ける", body: `最寒月 ${f(cold)}℃ は、18℃以上→A、−3℃以上18℃未満→C、−3℃未満→D のうち、{{${ZONES[z]}}}にあたります。`, trap: "冬の寒さがきびしくても、夏に10℃以上になれば寒帯ではなく亜寒帯です。", back: [S4] }]),
    ],
  };
}

