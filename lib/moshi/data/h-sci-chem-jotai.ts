const U = "h-sci-chem-jotai";
const L = (n: number, label: string) => ({ label, href: `/learn/lecture/${U}#lec-s${n}` });
const S1 = L(1, "三態は粒子の運動と分子間力で決まる");
const S2 = L(2, "とけている間・沸騰している間は温度が一定");
const S3 = L(3, "沸騰は「蒸気圧＝外圧」になったとき");
