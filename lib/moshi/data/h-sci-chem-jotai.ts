const f = (x: number) => String(Math.round(x * 1000) / 1000);

function yukai(r: Rng): QuestionBody {
  const melt = r.bool();
  const m = r.pick([4.5, 9, 13.5, 27, 36, 45, 54, 72, 90]);
  const n = m / 18;
  const H = melt ? 6.0 : 41;
  const q = f(n * H);
  return {
    prompt: melt
      ? `0℃ の氷 ${f(m)} g をすべて 0℃ の水にするのに必要な熱は何 kJ ですか。水の融解熱は 6.0 kJ/mol、H₂O＝18 とします。`
      : `100℃ の水 ${f(m)} g をすべて 100℃ の水蒸気にするのに必要な熱は何 kJ ですか。水の蒸発熱は 41 kJ/mol、H₂O＝18 とします。`,
    answer: { kind: "num", answerKind: "num", answer: [q], unit: "kJ", calc: `${m}/18*${H}` },
    point: "融解熱・蒸発熱は 1 mol あたり。まず mol に直す",
    steps: [
      { title: "mol に直す", body: `${f(m)}÷18＝{{${f(n)} mol}}。`, back: [S2] },
      { title: "1 mol あたりの熱をかける", body: `${f(n)}×${f(H)}＝{{${q} kJ}}。`, trap: "融解熱・蒸発熱を 1 g あたりの値とまちがえて、質量に直接かけない。", back: [S2] },
    ],
  };
}

function atatame(r: Rng): QuestionBody {
  const m = r.pick([9, 18, 27, 36, 45, 54, 90]);
  const t = r.pick([10, 20, 25, 30, 40, 50, 60]);
  const q1 = (m / 18) * 6.0;
  const q2 = (m * 4.2 * t) / 1000;
  const q = f(q1 + q2);
  return {
    prompt: `0℃ の氷 ${m} g を、すべて ${t}℃ の水にするのに必要な熱は何 kJ ですか。水の融解熱は 6.0 kJ/mol、水の比熱は 4.2 J/(g·K)、H₂O＝18 とします。`,
    answer: { kind: "num", answerKind: "num", answer: [q], unit: "kJ", calc: `${m}/18*6.0+${m}*4.2*${t}/1000` },
    point: "とかす熱（融解熱）と温める熱（質量×比熱×Δt）の和",
    steps: [
      { title: "とかす", body: `${m}÷18＝${f(m / 18)} mol。${f(m / 18)}×6.0＝{{${f(q1)} kJ}}（温度は0℃のまま）。`, back: [S2] },
      { title: "温める", body: `${m}×4.2×${t}＝${f(q2 * 1000)} J＝{{${f(q2)} kJ}}。`, trap: "比熱の式の答えは J。kJ に直してから足す。" },
      { title: "合計", body: `${f(q1)}＋${f(q2)}＝{{${q} kJ}}。` },
    ],
  };
}

function zenbu(r: Rng): QuestionBody {
  const m = r.pick([4.5, 9, 13.5, 18, 22.5, 27, 36, 45, 54]);
  const up = r.bool();
  const n = m / 18;
  const q1 = n * 6.0;
  const q2 = (m * 4.2 * 100) / 1000;
  const q3 = n * 41;
  const q = f(q1 + q2 + q3);
  return {
    prompt: up
      ? `0℃ の氷 ${f(m)} g を加熱して、すべて 100℃ の水蒸気にしました。必要な熱は全部で何 kJ ですか。水の融解熱 6.0 kJ/mol、蒸発熱 41 kJ/mol、水の比熱 4.2 J/(g·K)、H₂O＝18 とします。`
      : `100℃ の水蒸気 ${f(m)} g を冷やして、すべて 0℃ の氷にしました。このとき放出される熱は全部で何 kJ ですか（凝縮熱・凝固熱は、蒸発熱・融解熱と同じ大きさです）。水の融解熱 6.0 kJ/mol、蒸発熱 41 kJ/mol、水の比熱 4.2 J/(g·K)、H₂O＝18 とします。`,
    answer: { kind: "num", answerKind: "num", answer: [q], unit: "kJ", calc: `${m}/18*6.0+${m}*4.2*100/1000+${m}/18*41` },
    point: "融解・温度上昇・蒸発の3つの熱を足す",
    steps: [
      { title: "融解（0℃のまま）", body: `${f(n)} mol×6.0＝{{${f(q1)} kJ}}。`, back: [S2] },
      { title: "0℃→100℃", body: `${f(m)}×4.2×100 J＝{{${f(q2)} kJ}}。`, back: [S2] },
      { title: "蒸発（100℃のまま）と合計", body: `${f(n)}×41＝${f(q3)} kJ。合わせて ${f(q1)}＋${f(q2)}＋${f(q3)}＝{{${q} kJ}}。`, trap: "温度が一定の水平な部分にも熱は加わっている。融解と蒸発の熱を落とさない。" },
    ],
  };
}

