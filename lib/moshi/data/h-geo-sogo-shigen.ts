const res = (r: Rng) => r.pick(["鉱産資源X", "鉱物資源Y", "資源Z"]);

function kasai(r: Rng): QuestionBody {
  const years = r.int(15, 160);
  const prod = r.step(20, 900, 10);
  const reserve = years * prod;
  const x = res(r);
  return {
    prompt: `ある国の${x}の確認埋蔵量は ${reserve}万トン、1年間の生産量は ${prod}万トンです。このペースで生産を続けるとすると、${x}の可採年数は何年ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(years)], unit: "年", calc: `${reserve}/${prod}` },
    point: "可採年数＝確認埋蔵量÷1年間の生産量",
    steps: [{ title: "埋蔵量を1年分でわる", body: `${reserve}÷${prod}＝{{${years}}}（年）。いまのペースで何年もつかの目安です。`, trap: "生産量÷埋蔵量にしない。何年分あるかなので、埋蔵量を1年分でわります。", back: [S4] }],
  };
}

function kasaiHenka(r: Rng): QuestionBody {
  const y0 = r.int(20, 60);
  const p0 = r.step(50, 400, 10);
  const r0 = y0 * p0;
  const p1 = p0 + r.step(10, 100, 10);
  let y1 = y0 + r.int(5, 40);
  while (y1 * p1 <= r0) y1 += 5;
  const r1 = y1 * p1;
  const add = r1 - r0;
  const why = r.pick(["価格が上がって、これまで採算がとれなかった鉱床も掘り出せるようになり", "新しい掘り出し方の技術が開発され"]);
  const x = res(r);
  return {
    prompt: `ある国の${x}は、確認埋蔵量が ${r0}万トン、1年間の生産量が ${p0}万トンでした。その後、${why}、確認埋蔵量が ${add}万トンふえました。同時に、1年間の生産量も ${p1}万トンにふえました。このときの可採年数は何年ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(y1)], unit: "年", calc: `(${r0}+${add})/${p1}` },
    point: "確認埋蔵量は価格や技術でふえる",
    steps: [
      { title: "新しい確認埋蔵量", body: `${r0}＋${add}＝${r1}（万トン）。`, back: [S4] },
      { title: "新しい生産量でわる", body: `${r1}÷${p1}＝{{${y1}}}（年）。前の可採年数（${r0}÷${p0}＝${y0}年）より長くなりました。生産量がふえても、確認埋蔵量がそれ以上にふえれば可採年数はのびます。`, trap: "生産量を古い値（" + p0 + "万トン）のまま使わない。", back: [S4] },
    ],
  };
}

