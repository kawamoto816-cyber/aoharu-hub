function rishi(r: Rng): QuestionBody {
  const kind = r.pick(["gokei", "rishi", "yokin"] as const);
  if (kind === "yokin") {
    const d = r.step(10000, 100000, 10000);
    const pp = r.int(1, 3); // 0.1% 単位
    const p = String(pp / 10);
    const ri = (d * pp) / 1000;
    const who = r.pick(["中学生のハナさん", "中学生のリクさん", "高校生の姉", "小学生の弟"] as const);
    return {
      prompt: `${who}が、お年玉の${yen(d)}を、1年後に利子がつく金利（年利）${p}%の預金にしました。1年後に受け取る利子は何円ですか。`,
      answer: { kind: "num", answerKind: "num", answer: [String(ri)], unit: "円", calc: `${d}*${pp}/1000` },
      point: "利子＝元金×金利",
      steps: [
        { title: "元金×金利", body: `${d}円の${p}%は、${d}×${pp / 1000}＝{{${ri}}}（円）。`, back: [S2] },
        { title: "なぜ利子がつくのか", body: "預けたお金は銀行から企業や家計に貸し出され、利子を生んでいます。預金の利子は、そこから支払われます。" },
      ],
    };
  }
  const m = r.step(50, 500, 10); // 万円
  const p = r.int(1, 5);
  const gan = m * 10000;
  const ri = (gan * p) / 100;
  const tot = gan + ri;
  const b = r.pick(BORROWERS);
  const ask = kind === "gokei" ? "1年後に返す金額は、利子をふくめて合計何円ですか" : "1年後にはらう利子は何円ですか";
  return {
    prompt: `${b.who}が、${b.what}、銀行から${yen(gan)}を金利（年利）${p}%で1年間借りました。${ask}。`,
    answer: { kind: "num", answerKind: "num", answer: [String(kind === "gokei" ? tot : ri)], unit: "円", calc: kind === "gokei" ? `${gan}+${gan}*${p}/100` : `${gan}*${p}/100` },
    point: kind === "gokei" ? "返す金額＝元金＋利子" : "利子＝元金×金利",
    steps: [
      { title: "利子をもとめる", body: `借りたお金（元金）${yen(gan)}の${p}%は、${gan}×${p / 100}＝${kind === "rishi" ? `{{${ri}}}` : ri}（円）。`, back: [S2] },
      kind === "gokei"
        ? { title: "元金に利子を足す", body: `返す金額は、元金と利子の合計で ${gan}＋${ri}＝{{${tot}}}（円）。`, trap: "利子だけを答えにしない。借りたお金（元金）も返す。" }
        : { title: "元金と利子", body: `1年後には、元金と利子を合わせた${yen(tot)}を返します。銀行は、この貸し出しの利子と預金の利子の差を利益にしています。` },
    ],
  };
}

