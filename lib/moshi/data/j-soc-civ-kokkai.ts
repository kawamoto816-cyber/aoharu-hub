// ---- A: 再可決に必要な賛成者数 ----
function saikaketsuNinzu(r: Rng): QuestionBody {
  const n = r.step(300, 465, 3); // 3の倍数 (465 は衆議院の定数)
  const need = (n / 3) * 2;
  const what = r.pick(["否決した", "衆議院とちがう内容に修正して可決した"]);
  return {
    prompt: `衆議院で可決した法律案を、参議院が${what}ため、衆議院でもう一度採決することになりました。このとき衆議院の本会議には ${n}人の議員が出席していました。この法律案を成立させるには、最低何人の賛成が必要ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(need)], unit: "人", calc: `${n}*2/3` },
    point: "出席議員×2/3 以上で再可決",
    steps: [
      { title: "条件を確かめる", body: `再可決の条件は、衆議院の {{出席議員の3分の2以上}} の賛成です。`, trap: "総議員（465人）ではなく、その日の出席議員で計算する。", back: [S5] },
      { title: "計算する", body: `${n}×2/3＝{{${need}}}（人）。${need}人以上が賛成すれば、法律案は成立します。` },
    ],
  };
}

