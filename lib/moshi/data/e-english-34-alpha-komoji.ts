// 外国語活動（小3・4）「アルファベット（小文字）」の単元模試 (B: 問題プールからシードで選ぶ)。
// 問題はすべてオリジナル (教科書・ドリルの問題や、アルファベットの歌は使っていない)。
// 大問1「大文字と小文字のペア」・大問2「高さと向き」。
// それぞれプール6問 (基本2・標準2・発展2) から基本・標準・発展を1問ずつ。1回 6問・満点100 (基本15・標準17・発展18 × 2)。
// 選択問題は ch()、文字を書く問題は tm() で作る (小文字なので caseSensitive)。A (生成) は使っていないので検算式はなし。
// 小3・4 の単元なので、小3までに習わない漢字にはルビ《》をつける。
import type { QuestionB, UnitMoshi } from "../types";

const U = "e-english-34-alpha-komoji";
const L = (n: number, label: string) => ({ label, href: `/learn/lecture/${U}#lec-s${n}` });
type Back = ReturnType<typeof L>;
const S1 = L(1, "大文字と小文字は、名前が同じペア");
