// ---- 大問2 (A)：自己負担の計算 ----

const PEOPLE = ["30歳の会社員", "45歳の店員", "52歳の農家の人", "38歳の公務員", "60歳の自営業の人"] as const;
const BYOKI = ["かぜをこじらせて通院し", "足を骨折して手当てを受け", "歯の治療を受け", "胃の検査を受け", "腰を痛めて通院し"] as const;
const KAIGO = ["ホームヘルパーに自宅へ来てもらう", "デイサービスに通う", "ホームヘルパーとデイサービスを組み合わせて利用する"] as const;

function jikofutan(r: Rng): QuestionBody {
  const kind = r.pick(["madoguchi", "hoken", "sogaku", "kaigo"] as const);
  if (kind === "kaigo") {
    const c = r.step(30000, 200000, 10000);
    const f = c / 10;
    const what = r.pick(KAIGO);
    return {
      prompt: `介護が必要と認められた高齢者が、1か月に${what}サービスを受け、その費用は${c}円でした。利用者の負担を1割とすると、この高齢者が負担する金額は何円ですか。`,
      answer: { kind: "num", answerKind: "num", answer: [String(f)], unit: "円", calc: `${c}*1/10` },
      point: "介護サービスは費用の一部（1割など）を負担して利用",
      steps: [
        { title: "負担は費用の1割", body: `介護保険のサービスは、費用の一部を負担して利用します。${c}×0.1＝{{${f}}}（円）。`, back: [S3] },
        { title: "残りはだれが出すか", body: `残りの${c - f}円は、40歳以上の人が納めた {{保険料}} と税金で、およそ半分ずつまかなわれます。` },
      ],
    };
  }
  const t = r.step(3000, 30000, 1000);
  const w = (t * 3) / 10;
  const h = t - w;
  const who = r.pick(PEOPLE);
  const what = r.pick(BYOKI);
  if (kind === "sogaku") {
    return {
      prompt: `${who}が、${what}、病院の窓口で健康保険証（マイナンバーカード）を見せて${w}円をはらいました。窓口での負担を医療費の3割とすると、かかった医療費の総額は何円ですか。`,
      answer: { kind: "num", answerKind: "num", answer: [String(t)], unit: "円", calc: `${w}*10/3` },
      point: "窓口の負担＝医療費の3割 → 総額＝負担÷0.3",
      steps: [
        { title: "3割が何円か", body: `医療費の3割が${w}円なので、1割は ${w}÷3＝${w / 3}（円）。`, back: [S2] },
        { title: "総額をもとめる", body: `10割（総額）は ${w / 3}×10＝{{${t}}}（円）。残りの${h}円は医療保険から支払われます。`, trap: `${w}円に0.3をかけない。0.3をかけてもとめたのが${w}円。` },
      ],
    };
  }
  const ask = kind === "madoguchi" ? w : h;
  return {
    prompt: `${who}が、${what}、医療費が全部で${t}円かかりました。健康保険に加入していて、窓口での負担を医療費の3割とすると、${kind === "madoguchi" ? "窓口ではらう金額" : "医療保険から支払われる金額"}は何円ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(ask)], unit: "円", calc: kind === "madoguchi" ? `${t}*3/10` : `${t}*7/10` },
    point: "窓口で3割、残り7割は医療保険から",
    steps: [
      { title: "窓口の負担", body: `窓口では医療費の3割をはらいます。${t}×0.3＝${kind === "madoguchi" ? `{{${w}}}` : w}（円）。`, back: [S2] },
      {
        title: "保険から出る分",
        body: `残りの7割、${t}−${w}＝${kind === "madoguchi" ? h : `{{${h}}}`}（円）は、加入者みんなの {{保険料}} と、国や事業主の負担からまかなわれます。`,
        trap: kind === "hoken" ? "窓口ではらう3割と、保険から出る7割を取りちがえない。" : undefined,
      },
    ],
  };
}

