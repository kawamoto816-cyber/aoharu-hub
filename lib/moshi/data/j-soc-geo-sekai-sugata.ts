/** 地球の中心をはさんで反対側の地点の経度 (180−経度、東経と西経が入れかわる) */
function hantaigawa(r: Rng): QuestionBody {
  const lat = r.int(5, 70);
  const lon = r.int(10, 170);
  const north = r.bool();
  const east = r.bool();
  const name = r.pick(["地点A", "地点P", "地点X", "ある港町", "ある島"]);
  const ns = north ? "北緯" : "南緯";
  const ns2 = north ? "南緯" : "北緯";
  const ew = east ? "東経" : "西経";
  const ew2 = east ? "西経" : "東経";
  const ans = 180 - lon;
  return {
    prompt: `${name}は、${ns}${lat}度・${ew}${lon}度にあります。地球の中心をはさんで、そのちょうど反対側にある地点の経度を答えなさい。`,
    answer: { kind: "num", answerKind: "num", answer: [String(ans)], labels: [ew2], unit: "度", calc: `180-${lon}` },
    point: "反対側の経度は 180−経度、東経と西経が入れかわる",
    steps: [
      { title: "緯度は、数はそのまま南北が逆", body: `赤道をはさんで反対になるので、緯度は {{${ns2}${lat}度}} です。`, back: [S3] },
      {
        title: "経度は、180度から引く",
        body: `反対側の経線は、ちょうど半周（180度）まわった所。経度は東西それぞれ180度までなので、180−${lon}＝{{${ans}}}。${ew2}${ans}度です。`,
        trap: `${ew}${lon}度のまま、または${ew2}${lon}度としない。経度は東西それぞれ180度までなので、反対側は 180−${lon} になります。`,
        back: [S3],
      },
    ],
  };
}

/** 同じ経線上の2地点の距離 (地球一周4万km → 緯度1度あたり 40000/360 km) */
function kyori(r: Rng): QuestionBody {
  const k = r.int(2, 9);
  const diff = 9 * k;
  const cross = r.bool();
  let a: number; // 北の地点の緯度
  let b: number; // 南の地点の緯度
  if (cross) {
    a = r.int(1, diff - 1);
    b = diff - a;
  } else {
    b = r.int(0, 80 - diff);
    a = b + diff;
  }
  const ans = 1000 * k;
  const placeA = `北緯${a}度`;
  const placeB = cross ? `南緯${b}度` : b === 0 ? "赤道上" : `北緯${b}度`;
  const sa = cross ? `${a}＋${b}` : `${a}−${b}`;
  const calc = cross ? `40000*(${a}+${b})/360` : `40000*(${a}-${b})/360`;
  const who = r.pick(["同じ経線上にある2つの地点", "南北に真っすぐならんだ2つの町", "同じ経度にある2つの観測所"]);
  return {
    prompt: `${who}があり、一方は${placeA}、もう一方は${placeB}にあります。経線にそって測った2地点の間の距離は約何kmですか。地球一周（360度）を4万kmとして計算しなさい。`,
    answer: { kind: "num", answerKind: "num", answer: [String(ans)], labels: ["約"], unit: "km", calc },
    point: "緯度差を出し、4万km×緯度差÷360",
    steps: [
      {
        title: "緯度差を出す",
        body: cross ? `赤道をはさんで北と南にあるので、足して ${sa}＝{{${diff}度}}。` : `どちらも赤道より北なので、引いて ${sa}＝{{${diff}度}}。`,
        trap: cross ? `北緯と南緯で ${a}−${b} と引かない。赤道（0度）からのへだたりを足します。` : undefined,
        back: [S3],
      },
      { title: "一周のうちの何度分か", body: `経線は北極と南極を結ぶ円の一部で、一周360度で約4万km。${diff}度分は 40000×${diff}÷360＝{{${ans}}}（km）です。`, back: [S1] },
    ],
  };
}

