const f = (x: number) => String(Math.round(x * 1000) / 1000);

function omori(r: Rng): QuestionBody {
  const k = r.pick([6, 7, 7.5, 8, 8.4]);
  const t = r.int(3, 40);
  const d = k * t;
  return {
    prompt: `ある観測点で、初期微動継続時間（PS時間）が ${t} 秒であった。大森公式 D＝kT の比例定数 k を ${k} km/s とすると、震源距離 D は何 km ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [f(d)], unit: "km", calc: `${k}*${t}` },
    point: "震源距離 D＝k×PS時間 T",
    steps: [
      { title: "大森公式", body: "震源距離は PS時間に比例する：{{D＝kT}}。", back: [S2] },
      { title: "震源距離", body: `${k}×${t}＝{{${f(d)}}} km。` },
    ],
  };
}

/** [Vp, Vs, k] (k＝Vp·Vs/(Vp−Vs)) */
const V: [number, number, number][] = [[6, 3, 6], [8, 4, 8], [7, 3.5, 7], [6, 4, 12], [5, 3, 7.5], [6, 3.5, 8.4]];

function shingen(r: Rng): QuestionBody {
  const [vp, vs] = r.pick(V);
  const k = (vp * vs) / (vp - vs);
  const t = r.int(4, 30);
  const d = k * t;
  return {
    prompt: `P波の速さが ${vp} km/s、S波の速さが ${vs} km/s の地域で地震が起こった。ある観測点で P波が届いてから S波が届くまでの時間が ${t} 秒であったとき、震源距離は何 km ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [f(d)], unit: "km", calc: `${t}/(1/${vs}-1/${vp})` },
    point: "D/Vs−D/Vp＝T から D を求める",
    steps: [
      { title: "到着時刻の差", body: `距離 D を進む時間の差が PS時間：D/${vs}−D/${vp}＝${t}。`, back: [S2] },
      { title: "比例定数", body: `D(1/${vs}−1/${vp})＝${t} を整理すると D＝${vp}×${vs}÷(${vp}−${vs})×${t}。k＝${f(k)} km/s。` },
      { title: "震源距離", body: `D＝${f(k)}×${t}＝{{${f(d)}}} km。` },
    ],
  };
}

