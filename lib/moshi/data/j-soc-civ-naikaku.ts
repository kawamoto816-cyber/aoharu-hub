// ---- A: 国務大臣の過半数 ----
function kahansu(r: Rng): QuestionBody {
  const n = r.int(14, 19);
  const even = n % 2 === 0;
  const min = even ? n / 2 + 1 : (n + 1) / 2;
  const minCalc = even ? `${n}/2+1` : `(${n}+1)/2`;
  const half = n / 2;
  const halfText = even ? `${n}÷2＝${half} なので、${half}人ちょうどでは過半数にならず、{{${min}人}} 以上が必要` : `${n}÷2＝${half} なので、それより多い最小の整数 {{${min}人}} 以上が必要`;
  if (r.bool()) {
    return {
      prompt: `ある内閣で、内閣総理大臣が国務大臣を ${n}人任命します。憲法の決まりを守るには、このうち最低何人を国会議員から選ぶ必要がありますか。`,
      answer: { kind: "num", answerKind: "num", answer: [String(min)], unit: "人", calc: minCalc },
      point: "国務大臣の過半数＝半分より多く",
      steps: [
        { title: "決まりを確かめる", body: "国務大臣の {{過半数}} は国会議員でなければなりません。過半数とは「半分より多い」ことです。", back: [S1] },
        { title: "計算する", body: `${halfText}です。`, trap: "「半分」と「過半数」を同じにしない。" },
      ],
    };
  }
  const max = n - min;
  return {
    prompt: `ある内閣で、内閣総理大臣が国務大臣を ${n}人任命します。憲法の決まりを守るとき、国会議員でない人は最多で何人まで国務大臣にできますか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(max)], unit: "人", calc: `${n}-(${minCalc})` },
    point: "国会議員でない大臣＝全体−過半数の最少",
    steps: [
      { title: "国会議員の最少人数", body: `国務大臣の {{過半数}} は国会議員。${halfText}です。`, back: [S1] },
      { title: "残りが国会議員でない人", body: `${n}−${min}＝{{${max}}}（人）まで、国会議員でない人を大臣にできます。`, trap: "全員が国会議員でなければならない、と考えない。" },
    ],
  };
}

