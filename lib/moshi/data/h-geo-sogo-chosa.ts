const f = (x: number) => String(Math.round(x * 1000) / 1000);
const bunbo = (s: number) => (s === 25000 ? "2万5千" : s === 50000 ? "5万" : "1万");

function kyori(r: Rng): QuestionBody {
  const scale = r.pick([10000, 25000, 50000]);
  const len = r.step(1, 16, 0.5);
  const m = Math.round((len * scale) / 100);
  const what = r.pick(["駅から公民館まで", "学校から川の橋まで", "商店街の入り口から市役所まで", "バス停から神社まで"]);
  return {
    prompt: `縮尺${bunbo(scale)}分の1の地形図で、${what}の直線の長さをはかると ${f(len)}cm でした。実際の直線距離は何mですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(m)], unit: "m", calc: `${f(len)}*${scale}/100` },
    point: "実際の距離＝地図上の長さ×縮尺の分母",
    steps: [
      { title: "分母をかける", body: `${f(len)}cm×${scale}＝${f(len * scale)}cm。`, back: [S2, S3] },
      { title: "m に直す", body: `100cm＝1m なので、${f(len * scale)}÷100＝{{${m}}}（m）です。`, trap: "cm のまま答えたり、km に直しすぎたりしない。最後に単位を確かめます。", back: [S2] },
    ],
  };
}

function menseki(r: Rng): QuestionBody {
  const scale = r.pick([25000, 50000]);
  const side = scale === 25000 ? r.pick([2, 4, 6, 8]) : r.pick([1, 2, 3, 4, 5, 6]);
  const km = (side * scale) / 100000;
  const area = km * km;
  return {
    prompt: `縮尺${bunbo(scale)}分の1の地形図で、1辺が ${side}cm の正方形の範囲は、実際には何km² ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [f(area)], unit: "km²", calc: `(${side}*${scale}/100000)*(${side}*${scale}/100000)` },
    point: "面積は、実際の長さに直してからかける",
    steps: [
      { title: "1辺を実際の長さに", body: `${side}cm×${scale}＝${side * scale}cm＝{{${f(km)}km}}（100000cm＝1km）。`, back: [S2, S3] },
      { title: "面積を出す", body: `${f(km)}×${f(km)}＝{{${f(area)}}}（km²）です。`, trap: `${side}×${side}＝${side * side}cm² に分母をかけるだけでは、面積の倍率（分母の2乗）にならない。`, back: [S2] },
    ],
  };
}

