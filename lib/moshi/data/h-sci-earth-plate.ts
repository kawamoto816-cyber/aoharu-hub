function hayasa(r: Rng): QuestionBody {
  const v = r.pick([1, 2, 3, 4, 5, 6, 8, 10]);
  const t = r.step(100, 2000, 100); // 万年
  const d = (v * t * 10000) / 100000; // km
  return {
    prompt: `ある海嶺から ${d} km 離れた海底の玄武岩の年代は ${t} 万年前であった。この海底は、海嶺から片側へ平均して1年に何 cm の速さで移動してきたと考えられますか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(v)], unit: "cm/年", calc: `${d}*100000/(${t}*10000)` },
    point: "速さ＝海嶺からの距離÷岩石の年代（単位をそろえる）",
    steps: [
      { title: "単位をそろえる", body: `${d} km＝${d * 100000} cm、${t} 万年＝${t * 10000} 年。`, back: [S4] },
      { title: "速さ", body: `${d * 100000}÷${t * 10000}＝{{${v}}} cm/年。` },
    ],
  };
}

function nendai(r: Rng): QuestionBody {
  const v = r.pick([2, 3, 4, 5, 6, 8]);
  const t = r.step(50, 3000, 50); // 万年
  const d = (v * t) / 10; // km (v cm/年 × t万年)
  return {
    prompt: `ある海嶺では、海洋プレートが片側へ年に ${v} cm の速さで移動している。この海嶺から ${d} km 離れた海底の岩石は、何万年前にできたと考えられますか。速さは一定とする。`,
    answer: { kind: "num", answerKind: "num", answer: [String(t)], unit: "万年前", calc: `${d}*100000/${v}/10000` },
    point: "年代＝距離÷速さ",
    steps: [
      { title: "単位をそろえる", body: `${d} km＝${d * 100000} cm。`, back: [S4] },
      { title: "年代", body: `${d * 100000}÷${v}＝${t * 10000} 年＝{{${t}}} 万年前。海嶺から離れるほど古い。` },
    ],
  };
}

