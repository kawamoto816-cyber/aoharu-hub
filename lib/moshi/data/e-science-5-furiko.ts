// A は先に1往復の時間 (0.1秒きざみ) を決めてから10往復の時間を掛け算で作るので、答えは小数第2位までで割り切れる。
// calc で答えを検算 (scripts/check-moshi.ts がシード100個で確かめる)。長さと時間の値 (25cm 約1.0秒・50cm 約1.4秒・100cm 約2.0秒) はレクチャーにそろえた。
