const U = "e-science-5-furiko";
const L = (n: number, label: string) => ({ label, href: `/learn/lecture/${U}#lec-s${n}` });
const S = [L(1, "1往復とふりこの長さ"), L(2, "変える条件は1つずつ"), L(3, "長いふりこほど、ゆっくりゆれる"), L(4, "10往復をはかって、平均を出す"), L(5, "ふりこのきまりを使ったもの")];

/** 小数を「1.4」のように (末尾の0を出さない・誤差を出さない) */
const f = (x: number) => String(Math.round(x * 1000) / 1000);

function ichiOufuku(r: Rng): QuestionBody {
  const t10 = r.int(8, 24); // 1往復の10倍 (0.8〜2.4秒)
  const ten = t10; // 10往復の時間 (秒)
  const one = t10 / 10;
  const len = r.pick(["実験用の", "教室でつくった", "スタンドにつるした"]);
  return {
    prompt: `${len}ふりこを、手をはなしてから10往復させると、${ten}秒かかりました。このふりこの1往復の時間は何秒ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [f(one)], unit: "秒", calc: `${ten}/10` },
    point: "1往復の時間＝10往復の時間÷10",
    steps: [
      { title: "10往復を10でわる", body: `1往復は短いので、10往復の時間をはかって10でわります。${ten}÷10＝{{${f(one)}}}（秒）です。`, trap: "反対のはしに来たところで1回と数えると、半分しか数えていないことになります。", back: [S[3]] },
    ],
  };
}

function heikin(r: Rng): QuestionBody {
  // m: 10往復の平均 (0.1秒きざみ、整数で 120〜220 → 12.0〜22.0秒)。3回は m+d, m-d, m
  const m = r.int(120, 220);
  const d = r.int(1, 3);
  const a = (m + d) / 10;
  const b = (m - d) / 10;
  const c = m / 10;
  const avg = m / 10;
  const one = m / 100;
  return {
    prompt: `ふりこの10往復の時間を3回はかると、${f(a)}秒・${f(b)}秒・${f(c)}秒でした。3回の平均から、このふりこの1往復の時間を求めなさい。`,
    answer: { kind: "num", answerKind: "num", answer: [f(one)], unit: "秒", calc: `(${f(a)}+${f(b)}+${f(c)})/3/10` },
    point: "平均を出してから10でわる",
    steps: [
      { title: "3回の平均", body: `(${f(a)}＋${f(b)}＋${f(c)})÷3＝{{${f(avg)}}}（秒）。これが10往復の時間の平均です。`, back: [S[3]] },
      { title: "10往復を10でわる", body: `${f(avg)}÷10＝{{${f(one)}}}（秒）。これが1往復の時間です。`, trap: "平均の10往復のまま答えないように。聞かれているのは1往復の時間です。", back: [S[3]] },
    ],
  };
}

/** [長さcm, 1往復の約秒] (レクチャーの値) */
const NAGASA: [number, number][] = [
  [25, 1.0],
  [50, 1.4],
  [100, 2.0],
];

function joken(r: Rng): QuestionBody {
  const [len, t] = r.pick(NAGASA);
  const n = r.pick([10, 20, 30]);
  const kae = r.pick([
    { what: "おもりの重さを2倍にし、", why: "おもりの重さ" },
    { what: "ふれはばを大きくし、", why: "ふれはば" },
    { what: "おもりを同じ大きさの重いものに取りかえ、ふれはばも小さくして、", why: "おもりの重さとふれはば" },
  ]);
  const ans = t * n;
  return {
    prompt: `長さ${len}cmのふりこは、1往復に約${f(t)}秒かかります。このふりこの長さは変えずに、${kae.what}${n}往復させました。${n}往復にかかる時間は約何秒ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [f(ans)], labels: ["約"], unit: "秒", calc: `${f(t)}*${n}` },
    point: "1往復の時間を変えるのは、ふりこの長さだけ",
    steps: [
      { title: "変えたのは長さではない", body: `変えたのは${kae.why}だけです。1往復の時間を変えるのは{{ふりこの長さ}}だけなので、1往復は約${f(t)}秒のままです。`, trap: "重くすると速くなる・大きくふると時間が長くなる、と考えやすい。", back: [S[1]] },
      { title: `${n}往復の時間`, body: `${f(t)}×${n}＝{{${f(ans)}}}（秒）です。`, back: [S[3]] },
    ],
  };
}

