function password(r: Rng): QuestionBody {
  const [name, k] = r.pick([
    ["数字（0〜9）", 10],
    ["英小文字（26種類）", 26],
    ["英小文字と数字（36種類）", 36],
    ["英大文字（26種類）", 26],
  ] as const);
  const n = k === 10 ? r.int(4, 8) : r.int(3, 5);
  if (r.bool(0.3)) {
    return {
      prompt: `${name}だけを使う ${n}文字のパスワードを、1文字長くして ${n + 1}文字にした。考えられるパスワードの候補の数は何倍になりますか。`,
      answer: { kind: "num", answerKind: "num", answer: [String(k)], unit: "倍", calc: `${k}^${n + 1}/${k}^${n}` },
      point: "1文字ふえるごとに、文字の種類の数だけ倍になる",
      steps: [
        { title: "候補の数", body: `${n}文字なら ${k}^${n}、${n + 1}文字なら ${k}^${n + 1} 通り。`, back: [S4] },
        { title: "比べる", body: `${k}^${n + 1}÷${k}^${n}＝{{${k}}} 倍。`, trap: "2倍ではない。文字の種類の数だけ倍になる。" },
      ],
    };
  }
  const v = k ** n;
  return {
    prompt: `${name}だけを使う ${n}文字のパスワードは、全部で何通り考えられますか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(v)], unit: "通り", calc: `${k}^${n}` },
    point: "（文字の種類の数）を文字数だけかける",
    steps: [
      { title: "1文字ごとの選び方", body: `1文字ごとに ${k} 通りの選び方があります。`, back: [S4] },
      { title: "かけ合わせる", body: `${k} を ${n} 回かけて {{${v}}} 通り。`, trap: `${k}×${n} としない。かけ算ではなく累乗。` },
    ],
  };
}

