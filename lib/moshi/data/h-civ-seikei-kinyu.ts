/** 預金総額・信用創造額 */
function shinyoSozo(r: Rng): QuestionBody {
  const a = r.step(100, 900, 100);
  const rate = r.pick([5, 10, 20, 25, 50]);
  const total = (a * 100) / rate;
  const created = total - a;
  const askTotal = r.bool(0.4);
  return {
    prompt: `ある銀行に ${a}万円の預金（本源的預金）が預けられました。支払準備率が ${rate}% で、銀行は準備を除いた分をすべて貸し出し、貸し出されたお金はすべてどこかの銀行に預金されるとします。${askTotal ? "最終的な預金総額" : "新たに生まれた預金（信用創造額）"}は何万円ですか。`,
    answer: askTotal
      ? { kind: "num", answerKind: "num", answer: [String(total)], unit: "万円", calc: `${a}*100/${rate}` }
      : { kind: "num", answerKind: "num", answer: [String(created)], unit: "万円", calc: `${a}*100/${rate}-${a}` },
    point: "預金総額＝本源的預金÷支払準備率",
    steps: [
      { title: "預金総額", body: `${a}÷${rate / 100}＝{{${total}}}（万円）。初項 ${a}・公比 ${(100 - rate) / 100} の無限等比級数の和です。`, back: [S2] },
      {
        title: "信用創造額",
        body: `本源的預金を引いて ${total}−${a}＝{{${created}}}（万円）。`,
        trap: askTotal ? "信用創造額（総額−本源的預金）と取りちがえない。" : `預金総額（${total}万円）をそのまま答えない。`,
      },
    ],
  };
}

/** 支払準備率を変えたときの信用創造額の変化 */
function junbiritsu(r: Rng): QuestionBody {
  const [r1, r2] = r.pick([
    [5, 10],
    [10, 20],
    [10, 25],
    [20, 25],
    [20, 50],
    [25, 50],
  ] as const);
  const a = r.step(100, 600, 100);
  const c1 = (a * 100) / r1 - a;
  const c2 = (a * 100) / r2 - a;
  return {
    prompt: `本源的預金が ${a}万円のとき、支払準備率が ${r1}% から ${r2}% に引き上げられると、信用創造額は何万円減りますか（準備を除いた分はすべて貸し出され、すべて預金に戻るとします）。`,
    answer: { kind: "num", answerKind: "num", answer: [String(c1 - c2)], unit: "万円", calc: `(${a}*100/${r1}-${a})-(${a}*100/${r2}-${a})` },
    point: "準備率を上げると信用創造は小さくなる",
    steps: [
      { title: "引き上げ前", body: `${a}÷${r1 / 100}−${a}＝${c1}（万円）。`, back: [S2] },
      { title: "引き上げ後", body: `${a}÷${r2 / 100}−${a}＝${c2}（万円）。` },
      { title: "差", body: `${c1}−${c2}＝{{${c1 - c2}}}（万円）減ります。`, trap: "割る数（準備率）が大きくなるほど総額は小さくなる。準備率を上げると信用創造が増える、と考えない。" },
    ],
  };
}

