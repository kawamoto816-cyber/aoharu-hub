// ---- 大問2 (A): 直接請求の署名数 ----

/** 3けたごとにコンマ */
const comma = (n: number) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ",");

type Kind = { what: string; frac: 50 | 3; to: string };
function kinds(place: string): Kind[] {
  const head = place === "町" ? "町長" : "市長";
  return [
    { what: "条例の制定", frac: 50, to: "首長" },
    { what: "監査", frac: 50, to: "監査委員" },
    { what: `${head}の解職`, frac: 3, to: "選挙管理委員会" },
    { what: `${place}議会の解散`, frac: 3, to: "選挙管理委員会" },
  ];
}

function setup(r: Rng) {
  const n = r.int(4, 200) * 1500; // 6,000〜300,000人
  const place = n <= 15000 ? "町" : "市";
  const k = r.pick(kinds(place));
  const need = n / k.frac;
  return { n, place, k, need };
}

const fracText = (f: 50 | 3) => (f === 50 ? "50分の1以上" : "3分の1以上");

function hitsuyo(r: Rng): QuestionBody {
  const { n, place, k, need } = setup(r);
  return {
    prompt: `有権者が ${comma(n)}人の${place}で、住民が{{${k.what}}}を請求するために署名を集めます。必要な署名は、最低何人分ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(need)], unit: "人分", calc: `${n}/${k.frac}` },
    point: "条例・監査は1/50以上、解職・解散は1/3以上",
    steps: [
      { title: "必要な割合を決める", body: `${k.what}の請求は、有権者の {{${fracText(k.frac)}}} の署名が必要です。請求先は${k.to}です。`, back: [S3] },
      { title: "計算する", body: `${comma(n)}÷${k.frac}＝{{${comma(need)}}}（人分）以上です。`, trap: k.frac === 50 ? "人の地位にかかわらない請求なので、3分の1ではない。" : "選挙で選ばれた人の地位にかかわる請求なので、50分の1ではない。" },
    ],
  };
}

function nokori(r: Rng): QuestionBody {
  const { n, place, k, need } = setup(r);
  const d = r.int(1, Math.max(1, Math.floor(need / 20))) * 10; // 足りない人数 (10の倍数)
  const have = need - d;
  return {
    prompt: `有権者が ${comma(n)}人の${place}で、{{${k.what}}}を請求するための署名が ${comma(have)}人分集まりました。請求に必要な数にするには、少なくともあと何人分の署名が必要ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(d)], unit: "人分", calc: `${n}/${k.frac}-${have}` },
    point: "必要な署名数を出してから、集めた数を引く",
    steps: [
      { title: "必要な署名数", body: `${k.what}の請求は有権者の {{${fracText(k.frac)}}}。${comma(n)}÷${k.frac}＝${comma(need)}（人分）が必要です。`, back: [S3] },
      { title: "足りない数", body: `${comma(need)}−${comma(have)}＝{{${comma(d)}}}（人分）です。`, trap: "集めた数を有権者数から引かない。先に必要数を出す。" },
    ],
  };
}

