// ---- 大問2 (A)：税の計算 ----

/** 金額を「16万2000円」のように */
const yen = (n: number) => {
  const man = Math.floor(n / 10000);
  const rest = n % 10000;
  if (man === 0) return `${rest}円`;
  return rest === 0 ? `${man}万円` : `${man}万${rest}円`;
};

const FOODS = ["お弁当", "サンドイッチ", "おにぎりのセット", "カレーライス", "ハンバーガーのセット"] as const;
const OTHERS = ["ノート", "ボールペン", "タオル", "電池", "ハンカチ"] as const;
const STORES = ["コンビニエンスストア", "スーパーマーケット", "ショッピングセンターのフードコート"] as const;

function shohizei(r: Rng): QuestionBody {
  const food = r.pick(FOODS);
  const other = r.pick(OTHERS);
  const store = r.pick(STORES);
  const x = r.step(300, 900, 50); // 食料品 (税抜き)
  const y = r.step(100, 600, 10); // 食料品以外 (税抜き)
  const eatIn = r.bool(0.35); // 店内で食べる → 外食あつかいで10%
  const rate = eatIn ? 10 : 8;
  const fx = (x * (100 + rate)) / 100;
  const fy = (y * 110) / 100;
  const total = fx + fy;
  const how = eatIn ? "お店の中の席で食べることにしました" : "家に持ち帰ることにしました";
  return {
    prompt: `${store}で、税抜き${x}円の${food}と、税抜き${y}円の${other}を買い、${food}は${how}。消費税をふくめた代金の合計は何円ですか。消費税の税率は10%、軽減税率が適用されるものは8%とします。`,
    answer: { kind: "num", answerKind: "num", answer: [String(total)], unit: "円", calc: `${x}*${100 + rate}/100+${y}*110/100` },
    point: "持ち帰りの食料品は8%、店内での飲食と食料品以外は10%",
    steps: [
      {
        title: "それぞれの税率を決める",
        body: eatIn
          ? `${food}はお店の中で食べるので外食あつかいになり {{10%}}。${other}は食料品ではないので {{10%}}。`
          : `${food}は持ち帰りの食料品なので軽減税率の {{8%}}。${other}は食料品ではないので {{10%}}。`,
        trap: eatIn ? "同じ食べ物でも、店内で食べると外食になり軽減税率（8%）にならない。" : "食べ物ならいつでも8%ではない。店内で食べると10%になる。",
        back: [S4],
      },
      { title: "税こみの代金を足す", body: `${food} ${x}×${(100 + rate) / 100}＝${fx}（円）、${other} ${y}×1.1＝${fy}（円）。合計 ${fx}＋${fy}＝{{${total}}}（円）。` },
    ],
  };
}

function gyakushin(r: Rng): QuestionBody {
  const [na, nb] = r.pick([["Aさん", "Bさん"], ["Cさん", "Dさん"], ["Eさん", "Fさん"]] as const);
  const a = r.step(15, 30, 1); // 万円
  const ra = r.int(8, 10); // 収入のうち使う割合 (10分の ra)
  const b = r.step(50, 120, 10); // 万円
  const rb = r.int(2, 5);
  const incA = a * 10000;
  const incB = b * 10000;
  const spA = (incA * ra) / 10;
  const spB = (incB * rb) / 10;
  const taxA = spA / 10;
  const taxB = spB / 10;
  const pctA = (taxA / incA) * 100; // = ra
  const pctB = (taxB / incB) * 100; // = rb
  const diff = pctA - pctB;
  const useA = ra === 10 ? `収入の${yen(incA)}をすべて` : `収入${yen(incA)}のうち${yen(spA)}を`;
  return {
    prompt: `1か月に、${na}は${useA}生活のための買い物に使い、${nb}は収入${yen(incB)}のうち${yen(spB)}を買い物に使いました。使った金額の10%を消費税として負担したものとすると、収入にしめる消費税の割合は、${na}のほうが${nb}より何ポイント高いですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(diff)], unit: "ポイント", calc: `${taxA}/${incA}*100-${taxB}/${incB}*100` },
    point: "同じ税率でも、所得の低い人ほど負担の割合が高い＝逆進性",
    steps: [
      { title: "消費税の額", body: `${na}は ${yen(spA)}×10%＝${yen(taxA)}、${nb}は ${yen(spB)}×10%＝${yen(taxB)}。`, back: [S4] },
      { title: "収入にしめる割合", body: `${na}は ${yen(taxA)}÷${yen(incA)}＝${pctA}%、${nb}は ${yen(taxB)}÷${yen(incB)}＝${pctB}%。差は ${pctA}−${pctB}＝{{${diff}}}（ポイント）。`, trap: "税の金額は収入の多い人のほうが大きくても、収入にしめる割合でくらべる。" },
      { title: "逆進性", body: "所得の低い人ほど収入の多くを買い物に使うので、同じ税率でも所得にしめる税の割合が高くなります。この性質を {{逆進性}} といいます。" },
    ],
  };
}

