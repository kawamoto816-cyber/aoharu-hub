const H0 = [70, 70, 68, 72];

function kotai(r: Rng): QuestionBody {
  const h = r.pick(H0);
  const d = r.step(20, 600, 10);
  const v = h * d;
  return {
    prompt: `地球から ${d} Mpc（メガパーセク）の距離にある銀河は、およそ何 km/s の速さで遠ざかっていますか。ハッブル定数を ${h} km/s/Mpc とする。`,
    answer: { kind: "num", answerKind: "num", answer: [String(v)], unit: "km/s", calc: `${h}*${d}` },
    point: "後退速度 v＝H₀×距離 r",
    steps: [
      { title: "法則", body: "遠い銀河ほど速く遠ざかり、{{v＝H₀r}}（ハッブル・ルメートルの法則）。", back: [S3] },
      { title: "後退速度", body: `${h}×${d}＝{{${v}}} km/s。` },
    ],
  };
}

function kyori(r: Rng): QuestionBody {
  const h = r.pick(H0);
  const d = r.step(10, 800, 10);
  const v = h * d;
  return {
    prompt: `ある銀河のスペクトルを調べると、赤方偏移から後退速度が ${v} km/s とわかった。ハッブル定数を ${h} km/s/Mpc とすると、この銀河までの距離はおよそ何 Mpc（メガパーセク）ですか。`,
    answer: { kind: "num", answerKind: "num", answer: [String(d)], unit: "Mpc", calc: `${v}/${h}` },
    point: "距離 r＝v÷H₀",
    steps: [
      { title: "式を変形", body: "v＝H₀r より {{r＝v÷H₀}}。", back: [S3] },
      { title: "距離", body: `${v}÷${h}＝{{${d}}} Mpc。` },
    ],
  };
}

