// 地学「大気の運動」の単元模試 (A: 断熱減率・フェーン現象の計算3問 ＋ B: プール6問から3問)。問題はすべてオリジナル。
// 検算: 乾燥断熱減率 1℃/100m・湿潤断熱減率 0.5℃/100m (レクチャーの値) で、気温＝はじめの気温−1×(乾燥で上がった高さ)/100−0.5×(湿潤で上がった高さ)/100
//   (下降は＋1×高さ/100) を calc に書き、scripts/check-moshi.ts がシード1〜100で照合する。高さは 100 m 単位なので答えは小数第1位まで。
import type { QuestionB, QuestionBody, UnitMoshi } from "../types";
import type { Rng } from "../rng";

const U = "h-sci-earth-taiki";
const L = (n: number, label: string) => ({ label, href: `/learn/lecture/${U}#lec-s${n}` });
const S1 = L(1, "上昇する空気は膨張して冷える");
const S2 = L(2, "フェーン現象：山を越えると高温で乾いた風に");
const S3 = L(3, "大気の安定と不安定");
const S4 = L(4, "風を動かす力：気圧傾度力・転向力・摩擦力");
const S5 = L(5, "大気の大循環：熱を低緯度から高緯度へ運ぶ");

const f = (x: number) => String(Math.round(x * 1000) / 1000);
const D = (x: number) => f(x).replace("-", "−");
const NOTE = "乾燥断熱減率を 1℃/100m、湿潤断熱減率を 0.5℃/100m とする。";

function kanso(r: Rng): QuestionBody {
  const t0 = r.int(10, 32);
  const h = r.step(300, 2500, 100);
  const t = t0 - h / 100;
  return {
    prompt: `地表で気温 ${t0}℃ の、水蒸気で飽和していない空気のかたまりが、雲をつくらずに高さ ${h} m まで上昇した。このときの空気のかたまりの温度は何℃ですか。${NOTE}`,
    answer: { kind: "num", answerKind: "num", answer: [f(t)], unit: "℃", calc: `${t0}-1*${h}/100` },
    point: "飽和していない空気は 100 m で 1℃ 下がる",
    steps: [
      { title: "下がる温度", body: `飽和していないので{{乾燥断熱減率}}。${h} m で ${h / 100}℃ 下がる。`, back: [S1] },
      { title: "温度", body: `${t0}−${h / 100}＝{{${D(t)}}}℃。` },
    ],
  };
}

function sancho(r: Rng): QuestionBody {
  const t0 = r.int(14, 30);
  const hc = r.step(400, 1500, 100);
  const H = hc + r.step(400, 2000, 100);
  const t = t0 - hc / 100 - (0.5 * (H - hc)) / 100;
  return {
    prompt: `気温 ${t0}℃ の空気が、高さ 0 m のふもとから山の斜面にそって上昇した。高さ ${hc} m で雲ができはじめ、そのまま高さ ${H} m の山頂まで雲をつくりながら上昇した。山頂での空気の温度は何℃ですか。${NOTE}`,
    answer: { kind: "num", answerKind: "num", answer: [f(t)], unit: "℃", calc: `${t0}-1*${hc}/100-0.5*(${H}-${hc})/100` },
    point: "雲ができるまで 1℃/100m、雲ができてから 0.5℃/100m",
    steps: [
      { title: "雲ができるまで", body: `0〜${hc} m は乾燥断熱減率。${t0}−${hc / 100}＝${f(t0 - hc / 100)}℃。`, back: [S1] },
      { title: "雲ができてから", body: `${hc}〜${H} m の ${H - hc} m は湿潤断熱減率で ${f((0.5 * (H - hc)) / 100)}℃ 下がり、{{${D(t)}}}℃。`, back: [S2] },
    ],
  };
}

function fohn(r: Rng): QuestionBody {
  const t0 = r.int(14, 28);
  const hc = r.step(400, 1500, 100);
  const H = hc + r.step(400, 2000, 100);
  const top = t0 - hc / 100 - (0.5 * (H - hc)) / 100;
  const lee = top + H / 100;
  return {
    prompt: `風上側のふもと（高さ 0 m）で気温 ${t0}℃ の空気が山を越えた。風上側では高さ ${hc} m で雲ができ、山頂（${H} m）まで雲をつくりながら上昇し、雨を降らせた。山頂から風下側へは雲が消えて下降し、高さ 0 m のふもとに着いた。風下側のふもとでの気温は何℃ですか。${NOTE}`,
    answer: { kind: "num", answerKind: "num", answer: [f(lee)], unit: "℃", calc: `${t0}-1*${hc}/100-0.5*(${H}-${hc})/100+1*${H}/100` },
    point: "下降は雲がないので 1℃/100m で温まる",
    steps: [
      { title: "山頂の温度", body: `${t0}−${hc / 100}−${f((0.5 * (H - hc)) / 100)}＝${D(top)}℃。`, back: [S1] },
      { title: "風下へ下降", body: `雲がないので乾燥断熱減率で ${H / 100}℃ 上がる。${D(top)}＋${H / 100}＝{{${D(lee)}}}℃。風上より ${f(lee - t0)}℃ 高い（{{フェーン現象}}）。`, back: [S2] },
    ],
  };
}

