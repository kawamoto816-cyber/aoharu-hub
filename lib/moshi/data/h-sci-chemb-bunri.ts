function saikessho(r: Rng): QuestionBody {
  const w = r.pick([50, 100, 150, 200, 250, 300]);
  const sol = r.bool();
  const ans = f((77.4 * w) / 100);
  const given = sol ? `60℃の KNO₃ の飽和水溶液 ${f(2.09 * w)} g` : `60℃の水 ${w} g に KNO₃ を溶けるだけ溶かした飽和水溶液`;
  return {
    prompt: `硝酸カリウム KNO₃ は水100gに60℃で109g、20℃で31.6gまで溶けます。${given}を20℃まで冷やすと、KNO₃ の結晶は何 g 出てきますか。`,
    answer: { kind: "num", answerKind: "num", answer: [ans], unit: "g", calc: sol ? `${f(2.09 * w)}*(109-31.6)/209` : `(109-31.6)*${w}/100` },
    point: "水100gあたりの析出量 77.4g を、水の量に合わせて比例",
    steps: [
      { title: "水100gあたり", body: "水100gなら 109 − 31.6 ＝ {{77.4 g}} が溶けきれずに出てきます。", back: [S5] },
      sol
        ? { title: "飽和溶液の量から比例", body: `60℃の飽和溶液は水100gあたり 209 g。${f(2.09 * w)} g なら 77.4 × ${f(2.09 * w)}/209 ＝ {{${ans} g}}。`, trap: "溶液の質量を水の質量とみなさない。溶液は水＋溶質。" }
        : { title: "水の量に合わせる", body: `水 ${w} g なら 77.4 × ${w}/100 ＝ {{${ans} g}}。`, trap: "31.6 g を答えにしない。それは20℃でまだ溶けている量。" },
    ],
  };
}

