const f = (x: number) => String(Math.round(x * 1000) / 1000);

function kasui(r: Rng): QuestionBody {
  const kind = r.pick(["denpun", "cellulose", "sucrose"] as const);
  const n = r.pick([0.05, 0.1, 0.2, 0.25, 0.5, 1.0]);
  if (kind === "sucrose") {
    const w = f(n * 342);
    const g = f(n * 180);
    return {
      prompt: `スクロース C₁₂H₂₂O₁₁（分子量 342）${w} g を完全に加水分解しました。得られるグルコース C₆H₁₂O₆（分子量 180）は何 g ですか。`,
      answer: { kind: "num", answerKind: "num", answer: [g], unit: "g", calc: `${w}/342*180` },
      point: "スクロース 1 mol → グルコース 1 mol＋フルクトース 1 mol",
      steps: [
        { title: "加水分解", body: "{{C₁₂H₂₂O₁₁＋H₂O → C₆H₁₂O₆（グルコース）＋C₆H₁₂O₆（フルクトース）}}。できる混合物が転化糖。", back: [S2] },
        { title: "計算", body: `${w}÷342＝${f(n)} mol。グルコースも ${f(n)} mol で、×180＝{{${g} g}}。`, trap: "フルクトースの分まで足さない。聞かれているのはグルコースだけ。" },
      ],
    };
  }
  const name = kind === "denpun" ? "デンプン" : "セルロース";
  const w = f(n * 162);
  const g = f(n * 180);
  return {
    prompt: `${name} (C₆H₁₀O₅)ₙ ${w} g を完全に加水分解すると、グルコース C₆H₁₂O₆ は何 g 得られますか。H＝1.0、C＝12、O＝16 とします。`,
    answer: { kind: "num", answerKind: "num", answer: [g], unit: "g", calc: `${w}/162*180` },
    point: "くり返し単位 C₆H₁₀O₅（162）1つがグルコース1つに",
    steps: [
      { title: "くり返し単位", body: `C₆H₁₀O₅＝72＋10＋80＝{{162}}。${w}÷162＝${f(n)} mol 分。`, back: [S3] },
      { title: "水が加わる", body: `単位1つに H₂O が1つ加わってグルコース（180）になる。${f(n)}×180＝{{${g} g}}。`, trap: "加水分解で水の分だけ質量がふえる。もとの質量のままにしない。", back: [S1] },
    ],
  };
}

function peptide(r: Rng): QuestionBody {
  const a = r.int(1, 4);
  const b = r.int(1, 4);
  const k = a + b;
  const M = 75 * a + 89 * b - 18 * (k - 1);
  return {
    prompt: `グリシン（分子量 75）${a} 分子とアラニン（分子量 89）${b} 分子が、すべてペプチド結合で1本の鎖状につながったペプチドがあります。このペプチドの分子量を求めなさい。H₂O＝18 とします。`,
    answer: { kind: "num", answerKind: "num", answer: [String(M)], calc: `75*${a}+89*${b}-18*(${a}+${b}-1)` },
    point: "鎖状につながると、結合の数＝アミノ酸の数−1 だけ水がとれる",
    steps: [
      { title: "ペプチド結合の数", body: `アミノ酸は ${k} 分子。鎖状なのでペプチド結合は {{${k - 1} 個}}、とれる水も ${k - 1} 分子。`, back: [S4] },
      { title: "分子量", body: `75×${a}＋89×${b}−18×${k - 1}＝${75 * a + 89 * b}−${18 * (k - 1)}＝{{${M}}}。`, trap: `水を ${k} 分子引かない。鎖の両端の –NH₂ と –COOH は残る。` },
    ],
  };
}

