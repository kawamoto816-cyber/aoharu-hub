function signature(): string {
  const replyTo = process.env.SALES_REPLY_TO ?? "pr@bluespring.co.jp";
  return [
    "",
    "---",
    "株式会社ブルースプリング アオハルOS担当",
    `メール: ${replyTo}`,
    "https://app.bluespring.co.jp",
    "本メールが不要な場合はその旨ご返信ください。以後お送りしません。",
  ].join("\n");
}

