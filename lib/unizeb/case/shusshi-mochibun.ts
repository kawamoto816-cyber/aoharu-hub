// 月の利益：15万 − 6万 ＝ 9万円。年の利益：9万 × 12 ＝ 108万円
// 利益倍率 2〜4倍：108万 × 2 ＝ 216万円、108万 × 4 ＝ 432万円（3倍なら324万円）
// 申し出：出資後 100万 ÷ 0.3 ＝ 333.33…万円、出資前 333.33 − 100 ＝ 233.33…万円（約233万円。年の利益の約2.16倍）
//   株で：x ÷ (1,400 + x) ＝ 0.3 → x ＝ 600株、600 ÷ 2,000 ＝ 30%。2人は 1,400 ÷ 2,000 ＝ 70%（35%ずつ）
// 合意：出資前 400万円、出資後 500万円、100万 ÷ 500万 ＝ 20%（年の利益の約3.7倍、幅 216〜432万の中）
//   株で：1株 400万 ÷ 1,400 ＝ 2,857.14…円（約2,857円）、100万 ÷ 2,857.14 ＝ 350株、350 ÷ 1,750 ＝ 20%
//   2人：1,400 ÷ 1,750 ＝ 80%（700 ÷ 1,750 ＝ 40%ずつ）
// 次の調達（出資後10%と仮定）：
//   申し出の場合 2人 70% × 0.9 ＝ 63%、相手 30% × 0.9 ＝ 27%、新 10%（63 ＋ 27 ＋ 10 ＝ 100）
//   合意の場合   2人 80% × 0.9 ＝ 72%、相手 20% × 0.9 ＝ 18%、新 10%（72 ＋ 18 ＋ 10 ＝ 100）
//   3分の2 ＝ 66.66…%：63% は下回り、72% は上回る
// 申し出の30%は3分の1（33.3%）未満なので、相手は議決権だけでは特別の決議を止められない → だから契約の拒否権の範囲が大事
